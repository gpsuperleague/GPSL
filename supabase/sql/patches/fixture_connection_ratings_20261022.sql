-- =============================================================================
-- Fixture connection quality ratings (1–5 stars)
-- Soft feedback on Match Day result submit/confirm — about the connection
-- with the opponent, not the opponent themselves. Separate from network incidents.
-- Safe re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.competition_fixture_connection_ratings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id bigint NOT NULL REFERENCES public.competition_fixtures (id) ON DELETE CASCADE,
  season_id bigint NULL,
  gpsl_month text NULL,
  reporter_club_short_name text NOT NULL,
  opponent_club_short_name text NOT NULL,
  reporter_owner_id uuid NULL,
  stars smallint NOT NULL CHECK (stars BETWEEN 1 AND 5),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT competition_fixture_connection_ratings_unique
    UNIQUE (fixture_id, reporter_club_short_name)
);

CREATE INDEX IF NOT EXISTS competition_fixture_connection_ratings_season_idx
  ON public.competition_fixture_connection_ratings (season_id, created_at DESC);

CREATE INDEX IF NOT EXISTS competition_fixture_connection_ratings_stars_idx
  ON public.competition_fixture_connection_ratings (stars, created_at DESC);

CREATE INDEX IF NOT EXISTS competition_fixture_connection_ratings_opponent_idx
  ON public.competition_fixture_connection_ratings (opponent_club_short_name, stars);

COMMENT ON TABLE public.competition_fixture_connection_ratings IS
  'Per-club connection quality vs opponent on Match Day result submit/confirm (1–5). Not mid-match network incidents.';

ALTER TABLE public.competition_fixture_connection_ratings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS competition_fixture_connection_ratings_select
  ON public.competition_fixture_connection_ratings;
CREATE POLICY competition_fixture_connection_ratings_select
  ON public.competition_fixture_connection_ratings
  FOR SELECT
  TO authenticated
  USING (
    public.is_gpsl_admin()
    OR EXISTS (
      SELECT 1
      FROM public."Clubs" c
      WHERE c.owner_id = auth.uid()
        AND upper(c."ShortName") = upper(reporter_club_short_name)
    )
  );

DROP POLICY IF EXISTS competition_fixture_connection_ratings_admin
  ON public.competition_fixture_connection_ratings;
CREATE POLICY competition_fixture_connection_ratings_admin
  ON public.competition_fixture_connection_ratings
  FOR ALL
  TO authenticated
  USING (public.is_gpsl_admin())
  WITH CHECK (public.is_gpsl_admin());

CREATE OR REPLACE FUNCTION public.fixture_connection_rating_label(p_stars int)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $function$
  SELECT CASE p_stars
    WHEN 5 THEN 'Perfect'
    WHEN 4 THEN 'Great'
    WHEN 3 THEN 'Playable'
    WHEN 2 THEN 'Hard work'
    WHEN 1 THEN 'Unplayable'
    ELSE NULL
  END;
$function$;

CREATE OR REPLACE FUNCTION public.fixture_connection_rating_upsert(
  p_fixture_id bigint,
  p_stars int
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_club text;
  v_opp text;
  v_fx public.competition_fixtures%ROWTYPE;
  v_stars smallint := p_stars;
  v_id bigint;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_signed_in');
  END IF;

  IF p_fixture_id IS NULL OR v_stars IS NULL OR v_stars < 1 OR v_stars > 5 THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_stars');
  END IF;

  SELECT * INTO v_fx
  FROM public.competition_fixtures f
  WHERE f.id = p_fixture_id;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'no_fixture');
  END IF;

  SELECT c."ShortName" INTO v_club
  FROM public."Clubs" c
  WHERE c.owner_id = v_uid
  LIMIT 1;

  IF v_club IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'no_club');
  END IF;

  IF upper(v_club) = upper(v_fx.home_club_short_name) THEN
    v_opp := v_fx.away_club_short_name;
  ELSIF upper(v_club) = upper(v_fx.away_club_short_name) THEN
    v_opp := v_fx.home_club_short_name;
  ELSE
    RETURN jsonb_build_object('ok', false, 'reason', 'not_party');
  END IF;

  INSERT INTO public.competition_fixture_connection_ratings (
    fixture_id,
    season_id,
    gpsl_month,
    reporter_club_short_name,
    opponent_club_short_name,
    reporter_owner_id,
    stars,
    updated_at
  )
  VALUES (
    p_fixture_id,
    v_fx.season_id,
    v_fx.gpsl_month,
    v_club,
    v_opp,
    v_uid,
    v_stars,
    now()
  )
  ON CONFLICT (fixture_id, reporter_club_short_name) DO UPDATE SET
    stars = EXCLUDED.stars,
    opponent_club_short_name = EXCLUDED.opponent_club_short_name,
    reporter_owner_id = EXCLUDED.reporter_owner_id,
    season_id = EXCLUDED.season_id,
    gpsl_month = EXCLUDED.gpsl_month,
    updated_at = now()
  RETURNING id INTO v_id;

  RETURN jsonb_build_object(
    'ok', true,
    'id', v_id,
    'fixture_id', p_fixture_id,
    'stars', v_stars,
    'label', public.fixture_connection_rating_label(v_stars),
    'reporter_club_short_name', v_club,
    'opponent_club_short_name', v_opp
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_fixture_connection_ratings_list(
  p_season_id bigint DEFAULT NULL,
  p_max_stars int DEFAULT NULL,
  p_limit int DEFAULT 200
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_limit int := greatest(1, least(coalesce(p_limit, 200), 500));
  v_rows jsonb;
  v_summary jsonb;
BEGIN
  IF auth.uid() IS NOT NULL AND NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;

  SELECT coalesce(jsonb_agg(to_jsonb(x) ORDER BY x.stars ASC, x.created_at DESC), '[]'::jsonb)
  INTO v_rows
  FROM (
    SELECT
      r.id,
      r.fixture_id,
      r.season_id,
      s.label AS season_label,
      r.gpsl_month,
      f.competition_type,
      f.division,
      f.cup_code,
      f.matchday,
      f.status AS fixture_status,
      f.home_club_short_name,
      f.away_club_short_name,
      r.reporter_club_short_name,
      r.opponent_club_short_name,
      r.stars,
      public.fixture_connection_rating_label(r.stars) AS label,
      r.created_at,
      r.updated_at
    FROM public.competition_fixture_connection_ratings r
    LEFT JOIN public.competition_fixtures f ON f.id = r.fixture_id
    LEFT JOIN public.competition_seasons s ON s.id = r.season_id
    WHERE (p_season_id IS NULL OR r.season_id = p_season_id)
      AND (p_max_stars IS NULL OR r.stars <= p_max_stars)
    ORDER BY r.stars ASC, r.created_at DESC
    LIMIT v_limit
  ) x;

  -- Clubs most often named as the other side when rating is poor (1–2)
  SELECT coalesce(jsonb_agg(to_jsonb(y) ORDER BY y.poor_as_opponent DESC, y.avg_stars_as_opponent), '[]'::jsonb)
  INTO v_summary
  FROM (
    SELECT
      r.opponent_club_short_name AS club_short_name,
      count(*)::int AS ratings_as_opponent,
      count(*) FILTER (WHERE r.stars <= 2)::int AS poor_as_opponent,
      round(avg(r.stars)::numeric, 2) AS avg_stars_as_opponent
    FROM public.competition_fixture_connection_ratings r
    WHERE (p_season_id IS NULL OR r.season_id = p_season_id)
    GROUP BY r.opponent_club_short_name
    HAVING count(*) FILTER (WHERE r.stars <= 2) > 0
    ORDER BY count(*) FILTER (WHERE r.stars <= 2) DESC, avg(r.stars)
    LIMIT 40
  ) y;

  RETURN jsonb_build_object(
    'ok', true,
    'rows', v_rows,
    'poor_opponent_summary', v_summary,
    'row_count', jsonb_array_length(v_rows)
  );
END;
$function$;

