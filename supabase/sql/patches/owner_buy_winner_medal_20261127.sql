-- Owner buys an extra winner medal from personal wealth (Building Society).
-- Eligible: currently at the champion club, or on that club's archived
-- squad for the title season, and they do not already have the medal.
-- Automatic medals (5+ league apps, or 1+ app in that cup) are unchanged.

CREATE OR REPLACE FUNCTION public.winner_medal_price()
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT 5000::numeric;
$$;

CREATE TABLE IF NOT EXISTS public.competition_player_medal_purchases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id text NOT NULL,
  club_short_name text NOT NULL REFERENCES public."Clubs" ("ShortName"),
  season_id bigint NOT NULL REFERENCES public.competition_seasons (id) ON DELETE CASCADE,
  honour_type text NOT NULL CHECK (honour_type IN ('league_champion', 'cup_winner')),
  cup_code text,
  division text,
  owner_id uuid NOT NULL,
  amount numeric(14, 2) NOT NULL,
  ledger_id bigint,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS competition_player_medal_purchases_once
  ON public.competition_player_medal_purchases (
    player_id,
    season_id,
    honour_type,
    coalesce(cup_code, '')
  );

ALTER TABLE public.competition_player_medal_purchases ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.player_already_has_winner_medal(
  p_player_id text,
  p_season_id bigint,
  p_club text,
  p_honour_type text,
  p_cup_code text
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    EXISTS (
      SELECT 1
      FROM public.competition_player_medal_purchases m
      WHERE m.player_id = btrim(p_player_id)
        AND m.season_id = p_season_id
        AND m.honour_type = p_honour_type
        AND m.cup_code IS NOT DISTINCT FROM nullif(btrim(coalesce(p_cup_code, '')), '')
    )
    OR (
      p_honour_type = 'league_champion'
      AND public.competition_player_league_appearances(
        p_season_id, btrim(p_player_id), btrim(p_club)
      ) >= 5
    )
    OR (
      p_honour_type = 'cup_winner'
      AND nullif(btrim(coalesce(p_cup_code, '')), '') IS NOT NULL
      AND public.competition_player_cup_appearances(
        p_season_id, btrim(p_player_id), btrim(p_club), btrim(p_cup_code)
      ) >= 1
    );
$$;

CREATE OR REPLACE VIEW public.competition_player_honours_public
WITH (security_invoker = false)
AS
SELECT
  a.player_id,
  p."Name" AS player_name,
  h.club_short_name,
  h.club_name,
  h.season_id,
  h.season_label,
  h.honour_type,
  h.honour_label,
  h.division,
  h.cup_code,
  h.honoured_at
FROM public.competition_club_honours_public h
JOIN public.competition_player_season_archive a
  ON a.season_id = h.season_id
 AND a.club_short_name = h.club_short_name
JOIN public."Players" p ON p."Konami_ID"::text = a.player_id
WHERE (
    h.honour_type = 'league_champion'
    AND public.competition_player_league_appearances(
      a.season_id, a.player_id, a.club_short_name
    ) >= 5
  )
  OR (
    h.honour_type = 'cup_winner'
    AND h.cup_code IS NOT NULL
    AND public.competition_player_cup_appearances(
      a.season_id, a.player_id, a.club_short_name, h.cup_code
    ) >= 1
  )

UNION ALL

SELECT
  m.player_id,
  pl."Name" AS player_name,
  m.club_short_name,
  c."Club" AS club_name,
  m.season_id,
  h.season_label,
  m.honour_type,
  h.honour_label,
  h.division,
  m.cup_code,
  m.created_at AS honoured_at
FROM public.competition_player_medal_purchases m
JOIN public."Players" pl ON pl."Konami_ID"::text = m.player_id
JOIN public."Clubs" c ON c."ShortName" = m.club_short_name
JOIN public.competition_club_honours_public h
  ON h.season_id = m.season_id
 AND h.club_short_name = m.club_short_name
 AND h.honour_type = m.honour_type
 AND h.cup_code IS NOT DISTINCT FROM m.cup_code
WHERE NOT (
  (
    m.honour_type = 'league_champion'
    AND public.competition_player_league_appearances(
      m.season_id, m.player_id, m.club_short_name
    ) >= 5
  )
  OR (
    m.honour_type = 'cup_winner'
    AND m.cup_code IS NOT NULL
    AND public.competition_player_cup_appearances(
      m.season_id, m.player_id, m.club_short_name, m.cup_code
    ) >= 1
  )
);

GRANT SELECT ON public.competition_player_honours_public TO authenticated, anon;

CREATE OR REPLACE FUNCTION public.owner_winner_medal_shop()
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_owner uuid := auth.uid();
  v_club text;
  v_balance numeric;
  v_price numeric;
  v_honours jsonb;
BEGIN
  IF v_owner IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'Sign in required.');
  END IF;

  SELECT i.price INTO v_price
  FROM public.owners_shop_items i
  WHERE i.sku_code = 'winner_medal' AND i.is_active = true;
  IF v_price IS NULL THEN
    v_price := public.winner_medal_price();
  END IF;

  SELECT c."ShortName" INTO v_club
  FROM public."Clubs" c
  WHERE c.owner_id = v_owner
  LIMIT 1;

  IF v_club IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'No club on this account.');
  END IF;

  PERFORM public.owner_wallet_ensure(v_owner);
  SELECT w.balance INTO v_balance
  FROM public.owner_wallets w
  WHERE w.owner_id = v_owner;

  SELECT coalesce(jsonb_agg(row_to_json(x)::jsonb ORDER BY x.sort_label), '[]'::jsonb)
  INTO v_honours
  FROM (
    SELECT
      h.season_id,
      h.season_label,
      h.honour_type,
      h.honour_label,
      h.division,
      h.cup_code,
      h.honour_label || ' ' || h.season_label AS sort_label,
      (
        SELECT coalesce(jsonb_agg(jsonb_build_object(
          'player_id', cand.player_id,
          'name', cand.player_name,
          'where', cand.src
        ) ORDER BY cand.player_name), '[]'::jsonb)
        FROM (
          SELECT
            a.player_id,
            p."Name" AS player_name,
            'season'::text AS src
          FROM public.competition_player_season_archive a
          JOIN public."Players" p ON p."Konami_ID"::text = a.player_id
          WHERE a.season_id = h.season_id
            AND a.club_short_name = v_club
        ) cand
        WHERE NOT public.player_already_has_winner_medal(
          cand.player_id, h.season_id, v_club, h.honour_type, h.cup_code
        )
      ) AS players
    FROM public.competition_club_honours_public h
    WHERE h.club_short_name = v_club
  ) x;

  RETURN jsonb_build_object(
    'ok', true,
    'club', v_club,
    'price', v_price,
    'balance', coalesce(v_balance, 0),
    'honours', coalesce(v_honours, '[]'::jsonb)
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.owner_buy_winner_medal(
  p_player_id text,
  p_season_id bigint,
  p_honour_type text,
  p_cup_code text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_owner uuid := auth.uid();
  v_club text;
  v_price numeric := public.winner_medal_price();
  v_balance numeric;
  v_honour record;
  v_player_name text;
  v_pid text := btrim(coalesce(p_player_id, ''));
  v_type text := btrim(coalesce(p_honour_type, ''));
  v_cup text := nullif(btrim(coalesce(p_cup_code, '')), '');
  v_ledger bigint;
  v_id bigint;
BEGIN
  IF v_owner IS NULL THEN
    RAISE EXCEPTION 'Sign in required';
  END IF;
  IF v_pid = '' OR p_season_id IS NULL OR v_type NOT IN ('league_champion', 'cup_winner') THEN
    RAISE EXCEPTION 'Choose a player and a title';
  END IF;

  SELECT c."ShortName" INTO v_club
  FROM public."Clubs" c
  WHERE c.owner_id = v_owner
  LIMIT 1;
  IF v_club IS NULL THEN
    RAISE EXCEPTION 'No club on this account';
  END IF;

  SELECT h.honour_label, h.division, h.season_label, h.cup_code
  INTO v_honour
  FROM public.competition_club_honours_public h
  WHERE h.club_short_name = v_club
    AND h.season_id = p_season_id
    AND h.honour_type = v_type
    AND h.cup_code IS NOT DISTINCT FROM v_cup;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That title is not one of yours';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.competition_player_season_archive a
    WHERE a.player_id = v_pid
      AND a.season_id = p_season_id
      AND a.club_short_name = v_club
  ) THEN
    RAISE EXCEPTION 'That player was not in the squad for this title season';
  END IF;

  IF public.player_already_has_winner_medal(v_pid, p_season_id, v_club, v_type, v_cup) THEN
    RAISE EXCEPTION 'This player already has that medal';
  END IF;

  SELECT p."Name" INTO v_player_name
  FROM public."Players" p
  WHERE p."Konami_ID"::text = v_pid;

  SELECT i.price INTO v_price
  FROM public.owners_shop_items i
  WHERE i.sku_code = 'winner_medal'
    AND i.is_active = true;
  IF v_price IS NULL THEN
    v_price := public.winner_medal_price();
  END IF;

  PERFORM public.owner_wallet_ensure(v_owner);
  SELECT w.balance INTO v_balance
  FROM public.owner_wallets w
  WHERE w.owner_id = v_owner
  FOR UPDATE;
  IF coalesce(v_balance, 0) < v_price THEN
    RAISE EXCEPTION 'Not enough personal wealth. A medal costs % and the balance is %.',
      v_price, coalesce(v_balance, 0);
  END IF;

  INSERT INTO public.competition_player_medal_purchases (
    player_id, club_short_name, season_id, honour_type, cup_code, division,
    owner_id, amount
  )
  VALUES (
    v_pid, v_club, p_season_id, v_type, v_cup, v_honour.division,
    v_owner, v_price
  )
  RETURNING id INTO v_id;

  v_ledger := public._post_owner_ledger_internal(
    v_owner,
    'medal_purchase',
    -v_price,
    format('Winner medal — %s — %s', coalesce(v_player_name, v_pid), v_honour.honour_label),
    jsonb_build_object(
      'player_id', v_pid,
      'player_name', v_player_name,
      'club', v_club,
      'season_id', p_season_id,
      'season_label', v_honour.season_label,
      'honour_type', v_type,
      'honour_label', v_honour.honour_label,
      'cup_code', v_cup,
      'purchase_id', v_id
    ),
    p_season_id,
    true
  );

  UPDATE public.competition_player_medal_purchases
  SET ledger_id = v_ledger
  WHERE id = v_id;

  RETURN jsonb_build_object(
    'ok', true,
    'purchase_id', v_id,
    'price', v_price,
    'balance', round(coalesce(v_balance, 0) - v_price, 2),
    'player_name', v_player_name,
    'honour_label', v_honour.honour_label
  );
END;
$function$;

