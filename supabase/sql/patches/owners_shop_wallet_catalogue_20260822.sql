CREATE OR REPLACE FUNCTION public.admin_owners_shop_save_section(
  p_id bigint DEFAULT NULL,
  p_code text DEFAULT NULL,
  p_label text DEFAULT NULL,
  p_kicker text DEFAULT NULL,
  p_intro text DEFAULT NULL,
  p_theme_key text DEFAULT 'default',
  p_sort_order int DEFAULT 100,
  p_is_active boolean DEFAULT true
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_id bigint := p_id;
  v_code text := lower(btrim(coalesce(p_code, '')));
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  IF v_code = '' OR nullif(btrim(coalesce(p_label, '')), '') IS NULL THEN
    RAISE EXCEPTION 'code and label required';
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO public.owners_shop_sections (
      code, label, kicker, intro, theme_key, sort_order, is_active
    )
    VALUES (
      v_code,
      btrim(p_label),
      nullif(btrim(coalesce(p_kicker, '')), ''),
      nullif(btrim(coalesce(p_intro, '')), ''),
      coalesce(nullif(btrim(coalesce(p_theme_key, '')), ''), 'default'),
      coalesce(p_sort_order, 100),
      coalesce(p_is_active, true)
    )
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.owners_shop_sections
    SET
      code = v_code,
      label = btrim(p_label),
      kicker = nullif(btrim(coalesce(p_kicker, '')), ''),
      intro = nullif(btrim(coalesce(p_intro, '')), ''),
      theme_key = coalesce(nullif(btrim(coalesce(p_theme_key, '')), ''), 'default'),
      sort_order = coalesce(p_sort_order, 100),
      is_active = coalesce(p_is_active, true),
      updated_at = now()
    WHERE id = v_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Section % not found', v_id;
    END IF;
  END IF;

  RETURN jsonb_build_object('ok', true, 'id', v_id);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_owners_shop_save_item(
  p_id bigint DEFAULT NULL,
  p_section_id bigint DEFAULT NULL,
  p_sku_code text DEFAULT NULL,
  p_title text DEFAULT NULL,
  p_description text DEFAULT NULL,
  p_price numeric DEFAULT NULL,
  p_prize_type text DEFAULT NULL,
  p_param_int int DEFAULT NULL,
  p_quantity_granted int DEFAULT 1,
  p_badge_label text DEFAULT NULL,
  p_sort_order int DEFAULT 100,
  p_is_active boolean DEFAULT true,
  p_is_featured boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_id bigint := p_id;
  v_sku text := lower(btrim(coalesce(p_sku_code, '')));
  v_ptype text := lower(btrim(coalesce(p_prize_type, '')));
  v_price numeric(14, 2);
  v_pint int := p_param_int;
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  IF p_section_id IS NULL OR v_sku = '' OR nullif(btrim(coalesce(p_title, '')), '') IS NULL THEN
    RAISE EXCEPTION 'section_id, sku_code and title required';
  END IF;
  IF v_ptype NOT IN ('medical_token', 'fee_discount', 'appeal_card', 'draft_token') THEN
    RAISE EXCEPTION 'Invalid prize_type';
  END IF;

  v_price := round(coalesce(p_price, 0)::numeric, 2);
  IF v_price < 0 THEN
    RAISE EXCEPTION 'Price cannot be negative';
  END IF;

  IF v_ptype = 'appeal_card' THEN
    v_pint := NULL;
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO public.owners_shop_items (
      section_id, sku_code, title, description, price, prize_type, param_int,
      quantity_granted, badge_label, sort_order, is_active, is_featured
    )
    VALUES (
      p_section_id,
      v_sku,
      btrim(p_title),
      nullif(btrim(coalesce(p_description, '')), ''),
      v_price,
      v_ptype,
      v_pint,
      greatest(1, least(20, coalesce(p_quantity_granted, 1))),
      nullif(btrim(coalesce(p_badge_label, '')), ''),
      coalesce(p_sort_order, 100),
      coalesce(p_is_active, true),
      coalesce(p_is_featured, false)
    )
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.owners_shop_items
    SET
      section_id = p_section_id,
      sku_code = v_sku,
      title = btrim(p_title),
      description = nullif(btrim(coalesce(p_description, '')), ''),
      price = v_price,
      prize_type = v_ptype,
      param_int = v_pint,
      quantity_granted = greatest(1, least(20, coalesce(p_quantity_granted, 1))),
      badge_label = nullif(btrim(coalesce(p_badge_label, '')), ''),
      sort_order = coalesce(p_sort_order, 100),
      is_active = coalesce(p_is_active, true),
      is_featured = coalesce(p_is_featured, false),
      updated_at = now()
    WHERE id = v_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Item % not found', v_id;
    END IF;
  END IF;

  RETURN jsonb_build_object('ok', true, 'id', v_id);
END;
$function$;

-- ---------------------------------------------------------------------------
-- Buy + club stock
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.owners_shop_buy(p_item_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_club text;
  v_item public.owners_shop_items%ROWTYPE;
  v_bal numeric(14, 2);
  v_ledger_id bigint;
  v_inv_ids bigint[] := ARRAY[]::bigint[];
  v_inv_id bigint;
  v_i int;
  v_season_id bigint;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not signed in';
  END IF;
  IF p_item_id IS NULL THEN
    RAISE EXCEPTION 'Item required';
  END IF;

  SELECT * INTO v_item
  FROM public.owners_shop_items
  WHERE id = p_item_id AND is_active = true;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Item not available';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.owners_shop_sections s
    WHERE s.id = v_item.section_id AND s.is_active = true
  ) THEN
    RAISE EXCEPTION 'Section not available';
  END IF;

  v_club := public.my_club_shortname();
  IF v_club IS NULL OR v_club = '' THEN
    RAISE EXCEPTION 'No club linked — shop purchases stock on your current club';
  END IF;

  PERFORM public.owner_wallet_ensure(v_uid);

  SELECT balance INTO v_bal
  FROM public.owner_wallets
  WHERE owner_id = v_uid
  FOR UPDATE;

  IF coalesce(v_bal, 0) < v_item.price THEN
    RAISE EXCEPTION 'Insufficient owner balance (need %, have %)',
      v_item.price, coalesce(v_bal, 0);
  END IF;

  SELECT id INTO v_season_id
  FROM public.competition_seasons
  WHERE is_current = true
  ORDER BY id DESC
  LIMIT 1;

  v_ledger_id := public._post_owner_ledger_internal(
    v_uid,
    'shop_purchase',
    -abs(v_item.price),
    format('Owners Shop — %s → %s', v_item.title, v_club),
    jsonb_build_object(
      'source', 'owners_shop_buy',
      'item_id', v_item.id,
      'sku_code', v_item.sku_code,
      'club_short_name', v_club,
      'prize_type', v_item.prize_type,
      'param_int', v_item.param_int,
      'quantity_granted', v_item.quantity_granted
    ),
    v_season_id
  );

  FOR v_i IN 1..v_item.quantity_granted LOOP
    v_inv_id := public.prize_grant_inventory_item(
      v_club,
      v_item.prize_type,
      v_item.param_int,
      'owners_shop',
      v_season_id,
      NULL,
      jsonb_build_object(
        'shop_item_id', v_item.id,
        'sku_code', v_item.sku_code,
        'owner_id', v_uid,
        'ledger_id', v_ledger_id
      )
    );
    v_inv_ids := array_append(v_inv_ids, v_inv_id);
  END LOOP;

  SELECT balance INTO v_bal FROM public.owner_wallets WHERE owner_id = v_uid;

  RETURN jsonb_build_object(
    'ok', true,
    'ledger_id', v_ledger_id,
    'inventory_ids', to_jsonb(v_inv_ids),
    'club_short_name', v_club,
    'balance', coalesce(v_bal, 0),
    'item_title', v_item.title,
    'quantity', v_item.quantity_granted
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.owners_shop_club_stock(p_club text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_club text := nullif(btrim(coalesce(p_club, '')), '');
BEGIN
  IF v_club IS NULL THEN
    v_club := public.my_club_shortname();
  END IF;
  IF v_club IS NULL OR v_club = '' THEN
    RETURN '[]'::jsonb;
  END IF;
  IF NOT public.is_gpsl_admin()
     AND v_club IS DISTINCT FROM public.my_club_shortname() THEN
    RAISE EXCEPTION 'Not allowed';
  END IF;

  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object(
      'prize_type', x.prize_type,
      'param_int', x.param_int,
      'qty', x.qty
    ) ORDER BY x.prize_type, x.param_int NULLS LAST)
    FROM (
      SELECT prize_type, param_int, count(*)::int AS qty
      FROM public.club_prize_inventory
      WHERE club_short_name = v_club
        AND status = 'available'
        AND prize_type IN ('medical_token', 'appeal_card', 'fee_discount', 'draft_token')
