-- Owners Shop: personal wallet + admin catalogue + buy → club inventory
--
-- • owner_wallets / owner_finance_ledger — personal ₿ (not Club_Finances)
-- • owners_shop_sections / owners_shop_items — admin-configurable shelf
-- • owners_shop_buy — debit owner, grant club_prize_inventory via prize_grant
--
-- Run in Supabase SQL Editor. Safe re-run.
-- Prerequisites: gpsl_owner_registry, club_prize_inventory, prize_grant_inventory_item,
--                is_gpsl_admin(), my_club_shortname()
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Owner wallet + ledger
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.owner_wallets (
  owner_id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  balance numeric(14, 2) NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.owner_finance_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  entry_type text NOT NULL,
  amount numeric(14, 2) NOT NULL,
  description text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  season_id bigint REFERENCES public.competition_seasons (id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS owner_finance_ledger_owner_created_idx
  ON public.owner_finance_ledger (owner_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS owner_finance_ledger_type_idx
  ON public.owner_finance_ledger (entry_type);

ALTER TABLE public.owner_wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.owner_finance_ledger ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS owner_wallets_select_self_or_admin ON public.owner_wallets;
CREATE POLICY owner_wallets_select_self_or_admin ON public.owner_wallets
  FOR SELECT TO authenticated
  USING (owner_id = auth.uid() OR public.is_gpsl_admin());

DROP POLICY IF EXISTS owner_finance_ledger_select_self_or_admin ON public.owner_finance_ledger;
CREATE POLICY owner_finance_ledger_select_self_or_admin ON public.owner_finance_ledger
  FOR SELECT TO authenticated
  USING (owner_id = auth.uid() OR public.is_gpsl_admin());

CREATE OR REPLACE FUNCTION public.owner_wallet_ensure(p_owner_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF p_owner_id IS NULL THEN
    RAISE EXCEPTION 'Owner required';
  END IF;
  INSERT INTO public.owner_wallets (owner_id, balance)
  VALUES (p_owner_id, 0)
  ON CONFLICT (owner_id) DO NOTHING;
END;
$function$;

-- Internal poster (shop buy, admin adjust, future bookies/GPFL). Not granted to clients.
CREATE OR REPLACE FUNCTION public._post_owner_ledger_internal(
  p_owner_id uuid,
  p_entry_type text,
  p_amount numeric,
  p_description text DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb,
  p_season_id bigint DEFAULT NULL,
  p_apply_balance boolean DEFAULT true
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_amt numeric(14, 2);
  v_ledger_id bigint;
  v_season_id bigint := p_season_id;
BEGIN
  IF p_owner_id IS NULL THEN
    RAISE EXCEPTION 'Owner required';
  END IF;
  IF p_entry_type IS NULL OR btrim(p_entry_type) = '' THEN
    RAISE EXCEPTION 'entry_type required';
  END IF;

  v_amt := round(coalesce(p_amount, 0)::numeric, 2);
  IF v_amt = 0 THEN
    RAISE EXCEPTION 'Ledger amount cannot be zero';
  END IF;

  PERFORM public.owner_wallet_ensure(p_owner_id);

  IF v_season_id IS NULL THEN
    SELECT id INTO v_season_id
    FROM public.competition_seasons
    WHERE is_current = true
    ORDER BY id DESC
    LIMIT 1;
  END IF;

  INSERT INTO public.owner_finance_ledger (
    owner_id, entry_type, amount, description, metadata, season_id
  )
  VALUES (
    p_owner_id,
    btrim(p_entry_type),
    v_amt,
    nullif(btrim(coalesce(p_description, '')), ''),
    coalesce(p_metadata, '{}'::jsonb),
    v_season_id
  )
  RETURNING id INTO v_ledger_id;

  IF coalesce(p_apply_balance, true) THEN
    UPDATE public.owner_wallets
    SET
      balance = round(balance + v_amt, 2),
      updated_at = now()
    WHERE owner_id = p_owner_id;
  END IF;

  RETURN v_ledger_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.owner_wallet_get_self()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_bal numeric(14, 2);
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not signed in';
  END IF;
  PERFORM public.owner_wallet_ensure(v_uid);
  SELECT balance INTO v_bal FROM public.owner_wallets WHERE owner_id = v_uid;
  RETURN jsonb_build_object(
    'owner_id', v_uid,
    'balance', coalesce(v_bal, 0)
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_owner_wallet_adjust(
  p_owner_id uuid,
  p_amount numeric,
  p_description text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_amt numeric(14, 2);
  v_ledger_id bigint;
  v_bal numeric(14, 2);
  v_type text;
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  IF p_owner_id IS NULL THEN
    RAISE EXCEPTION 'Owner required';
  END IF;

  v_amt := round(coalesce(p_amount, 0)::numeric, 2);
  IF v_amt = 0 THEN
    RAISE EXCEPTION 'Amount cannot be zero';
  END IF;

  v_type := CASE WHEN v_amt > 0 THEN 'admin_credit' ELSE 'admin_debit' END;
  v_ledger_id := public._post_owner_ledger_internal(
    p_owner_id,
    v_type,
    v_amt,
    coalesce(nullif(btrim(coalesce(p_description, '')), ''), 'Admin wallet adjustment'),
    jsonb_build_object('source', 'admin_owner_wallet_adjust')
  );

  SELECT balance INTO v_bal FROM public.owner_wallets WHERE owner_id = p_owner_id;
  RETURN jsonb_build_object(
    'ok', true,
    'ledger_id', v_ledger_id,
    'balance', coalesce(v_bal, 0)
  );
END;
$function$;

