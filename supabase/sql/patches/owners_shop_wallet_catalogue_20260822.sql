  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id bigint NOT NULL REFERENCES public.owners_shop_sections (id) ON DELETE CASCADE,
  sku_code text NOT NULL UNIQUE,
  title text NOT NULL,
  description text,
  price numeric(14, 2) NOT NULL CHECK (price >= 0),
  prize_type text NOT NULL
    CHECK (prize_type IN ('medical_token', 'fee_discount', 'appeal_card', 'draft_token')),
  param_int int,
  quantity_granted int NOT NULL DEFAULT 1 CHECK (quantity_granted >= 1 AND quantity_granted <= 20),
  badge_label text,
  sort_order int NOT NULL DEFAULT 100,
  is_active boolean NOT NULL DEFAULT true,
  is_featured boolean NOT NULL DEFAULT false,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT owners_shop_items_param_check CHECK (
    (prize_type = 'medical_token' AND param_int IN (2, 4, 6, 8, 10))
    OR (prize_type = 'fee_discount' AND param_int > 0 AND param_int <= 50)
    OR (prize_type = 'appeal_card' AND param_int IS NULL)
    OR (prize_type = 'draft_token' AND (param_int IS NULL OR param_int > 0))
  )
);

