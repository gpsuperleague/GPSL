CREATE OR REPLACE FUNCTION public.owners_shop_catalogue(p_include_inactive boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_admin boolean := coalesce(public.is_gpsl_admin(), false);
  v_inc boolean := coalesce(p_include_inactive, false) AND v_admin;
BEGIN
  RETURN coalesce((
    SELECT jsonb_agg(
      jsonb_build_object(
        'id', s.id,
        'code', s.code,
        'label', s.label,
        'kicker', s.kicker,
        'intro', s.intro,
        'theme_key', s.theme_key,
        'sort_order', s.sort_order,
        'is_active', s.is_active,
        'items', coalesce((
          SELECT jsonb_agg(
            jsonb_build_object(
              'id', i.id,
              'sku_code', i.sku_code,
              'title', i.title,
              'description', i.description,
              'price', i.price,
              'prize_type', i.prize_type,
              'param_int', i.param_int,
              'quantity_granted', i.quantity_granted,
              'badge_label', i.badge_label,
              'sort_order', i.sort_order,
              'is_active', i.is_active,
              'is_featured', i.is_featured
            )
            ORDER BY i.sort_order, i.id
          )
          FROM public.owners_shop_items i
          WHERE i.section_id = s.id
            AND (v_inc OR i.is_active)
        ), '[]'::jsonb)
      )
      ORDER BY s.sort_order, s.id
    )
    FROM public.owners_shop_sections s
    WHERE v_inc OR s.is_active
  ), '[]'::jsonb);
END;
$function$;

