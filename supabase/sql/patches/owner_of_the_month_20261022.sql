-- =============================================================================
-- GPSL Owner of the Month — Super League + Championship (separate awards).
-- Best league record in a GPSL month among owned clubs in that division band.
-- Awarded when Manager of the Month runs (End GPSL Month / motm stage).
-- Safe re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.competition_owner_month_award (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.competition_seasons (id) ON DELETE CASCADE,
  season_label text NOT NULL,
  gpsl_month text NOT NULL,
  division_scope text NOT NULL CHECK (division_scope IN ('superleague', 'championship')),
  owner_id uuid NOT NULL,
  owner_tag text NOT NULL,
  club_short_name text NOT NULL REFERENCES public."Clubs" ("ShortName"),
  played smallint NOT NULL DEFAULT 0,
  won smallint NOT NULL DEFAULT 0,
  drawn smallint NOT NULL DEFAULT 0,
  lost smallint NOT NULL DEFAULT 0,
  gf smallint NOT NULL DEFAULT 0,
  ga smallint NOT NULL DEFAULT 0,
  pts smallint NOT NULL DEFAULT 0,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT competition_owner_month_award_unique
    UNIQUE (season_id, gpsl_month, division_scope)
);

CREATE INDEX IF NOT EXISTS competition_owner_month_award_owner_idx
  ON public.competition_owner_month_award (owner_id, season_id DESC);

CREATE INDEX IF NOT EXISTS competition_owner_month_award_month_idx
  ON public.competition_owner_month_award (season_id, gpsl_month, division_scope);

ALTER TABLE public.competition_owner_month_award ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS competition_owner_month_award_select ON public.competition_owner_month_award;
CREATE POLICY competition_owner_month_award_select ON public.competition_owner_month_award
  FOR SELECT TO authenticated, anon USING (true);

DROP POLICY IF EXISTS competition_owner_month_award_admin ON public.competition_owner_month_award;
CREATE POLICY competition_owner_month_award_admin ON public.competition_owner_month_award
  FOR ALL TO authenticated
  USING (public.is_gpsl_admin())
  WITH CHECK (public.is_gpsl_admin());

DROP VIEW IF EXISTS public.competition_owner_month_awards_public;
CREATE VIEW public.competition_owner_month_awards_public
WITH (security_invoker = false)
AS
SELECT
  a.id,
  a.season_id,
  a.season_label,
  a.gpsl_month,
  a.division_scope,
  a.owner_id,
  a.owner_tag,
  a.club_short_name,
  c."Club" AS club_name,
  a.played,
  a.won,
  a.drawn,
  a.lost,
  a.gf,
  a.ga,
  a.pts,
  a.detail,
  a.created_at
FROM public.competition_owner_month_award a
LEFT JOIN public."Clubs" c ON c."ShortName" = a.club_short_name;

GRANT SELECT ON public.competition_owner_month_awards_public TO authenticated;
GRANT SELECT ON public.competition_owner_month_awards_public TO anon;

CREATE OR REPLACE FUNCTION public.competition_compute_owner_of_month(
  p_season_id bigint,
  p_gpsl_month text,
  p_division_scope text DEFAULT 'superleague'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_month text := lower(nullif(btrim(coalesce(p_gpsl_month, '')), ''));
  v_scope text := lower(nullif(btrim(coalesce(p_division_scope, '')), ''));
  v_season_label text;
  v_best record;
  v_owner_id uuid;
  v_owner_tag text;
BEGIN
  IF p_season_id IS NULL OR v_month IS NULL OR v_month = 'playoffs' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_args');
  END IF;

  IF v_scope IS DISTINCT FROM 'superleague' AND v_scope IS DISTINCT FROM 'championship' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_scope');
  END IF;

  SELECT s.label INTO v_season_label
  FROM public.competition_seasons s
  WHERE s.id = p_season_id;

  WITH club_month AS (
    SELECT
      x.club_short_name,
      count(*)::smallint AS played,
      count(*) FILTER (WHERE x.pts = 3)::smallint AS won,
      count(*) FILTER (WHERE x.pts = 1)::smallint AS drawn,
      count(*) FILTER (WHERE x.pts = 0)::smallint AS lost,
      coalesce(sum(x.gf), 0)::smallint AS gf,
      coalesce(sum(x.ga), 0)::smallint AS ga,
      coalesce(sum(x.pts), 0)::smallint AS pts
    FROM (
      SELECT
        f.home_club_short_name AS club_short_name,
        coalesce(f.home_goals, 0) AS gf,
        coalesce(f.away_goals, 0) AS ga,
        CASE
          WHEN f.home_goals > f.away_goals THEN 3
          WHEN f.home_goals = f.away_goals THEN 1
          ELSE 0
        END AS pts
      FROM public.competition_fixtures f
      WHERE f.season_id = p_season_id
        AND f.gpsl_month = v_month
        AND f.competition_type = 'league'
        AND f.status = 'played'
        AND f.home_goals IS NOT NULL
        AND f.away_goals IS NOT NULL
      UNION ALL
      SELECT
        f.away_club_short_name,
        coalesce(f.away_goals, 0),
        coalesce(f.home_goals, 0),
        CASE
          WHEN f.away_goals > f.home_goals THEN 3
          WHEN f.away_goals = f.home_goals THEN 1
          ELSE 0
        END
      FROM public.competition_fixtures f
      WHERE f.season_id = p_season_id
        AND f.gpsl_month = v_month
        AND f.competition_type = 'league'
        AND f.status = 'played'
        AND f.home_goals IS NOT NULL
        AND f.away_goals IS NOT NULL
    ) x
    INNER JOIN public.competition_club_seasons s
      ON s.season_id = p_season_id
     AND s.club_short_name = x.club_short_name
     AND (
       (v_scope = 'superleague' AND s.division = 'superleague')
       OR (
         v_scope = 'championship'
         AND s.division IN ('championship_a', 'championship_b')
       )
     )
    GROUP BY x.club_short_name
    HAVING count(*) > 0
  )
  SELECT cm.*
  INTO v_best
  FROM club_month cm
  INNER JOIN public."Clubs" c ON c."ShortName" = cm.club_short_name
  WHERE c.owner_id IS NOT NULL
  ORDER BY cm.pts DESC, (cm.gf - cm.ga) DESC, cm.gf DESC, cm.club_short_name
  LIMIT 1;

  IF v_best.club_short_name IS NULL THEN
    RETURN jsonb_build_object(
      'ok', false,
      'reason', 'no_fixtures',
      'division_scope', v_scope,
      'gpsl_month', v_month
    );
  END IF;

  SELECT c.owner_id INTO v_owner_id
  FROM public."Clubs" c
  WHERE c."ShortName" = v_best.club_short_name;

  IF v_owner_id IS NULL THEN
    RETURN jsonb_build_object(
      'ok', false,
      'reason', 'no_owner',
      'division_scope', v_scope,
      'club_short_name', v_best.club_short_name
    );
  END IF;

  v_owner_tag := coalesce(
    nullif(btrim(public.owner_registry_resolve_tag(v_owner_id)), ''),
    'Owner'
  );

  INSERT INTO public.competition_owner_month_award (
    season_id, season_label, gpsl_month, division_scope,
    owner_id, owner_tag, club_short_name,
    played, won, drawn, lost, gf, ga, pts, detail
  )
  VALUES (
    p_season_id,
    coalesce(v_season_label, 'Season'),
    v_month,
    v_scope,
    v_owner_id,
    v_owner_tag,
    v_best.club_short_name,
    v_best.played,
    v_best.won,
    v_best.drawn,
    v_best.lost,
    v_best.gf,
    v_best.ga,
    v_best.pts,
    jsonb_build_object('gd', v_best.gf - v_best.ga)
  )
  ON CONFLICT (season_id, gpsl_month, division_scope) DO UPDATE SET
    owner_id = EXCLUDED.owner_id,
    owner_tag = EXCLUDED.owner_tag,
    club_short_name = EXCLUDED.club_short_name,
    played = EXCLUDED.played,
    won = EXCLUDED.won,
    drawn = EXCLUDED.drawn,
    lost = EXCLUDED.lost,
    gf = EXCLUDED.gf,
    ga = EXCLUDED.ga,
    pts = EXCLUDED.pts,
    detail = EXCLUDED.detail,
    season_label = EXCLUDED.season_label;

  RETURN jsonb_build_object(
    'ok', true,
    'gpsl_month', v_month,
    'division_scope', v_scope,
    'owner_id', v_owner_id,
    'owner_tag', v_owner_tag,
    'club_short_name', v_best.club_short_name,
    'pts', v_best.pts,
    'record', format('%s-%s-%s', v_best.won, v_best.drawn, v_best.lost)
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.competition_award_owners_of_month(
  p_season_id bigint,
  p_gpsl_month text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_sl jsonb;
  v_ch jsonb;
BEGIN
  v_sl := public.competition_compute_owner_of_month(p_season_id, p_gpsl_month, 'superleague');
  v_ch := public.competition_compute_owner_of_month(p_season_id, p_gpsl_month, 'championship');
  RETURN jsonb_build_object(
    'ok', true,
    'superleague', v_sl,
    'championship', v_ch
  );
END;
$function$;

GRANT EXECUTE ON FUNCTION public.competition_compute_owner_of_month(bigint, text, text)
  TO authenticated;
GRANT EXECUTE ON FUNCTION public.competition_award_owners_of_month(bigint, text)
  TO authenticated;

-- Hook: when MotM is computed on month lock, award Owner of the Month too.
CREATE OR REPLACE FUNCTION public.competition_compute_manager_of_month(
  p_season_id bigint,
  p_gpsl_month text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_month text := lower(nullif(btrim(coalesce(p_gpsl_month, '')), ''));
  v_season_label text;
  v_best record;
  v_manager_id bigint;
  v_manager_name text;
  v_motm jsonb;
  v_ootm jsonb;
BEGIN
  IF p_season_id IS NULL OR v_month IS NULL OR v_month = 'playoffs' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_args');
  END IF;

  SELECT s.label INTO v_season_label
  FROM public.competition_seasons s
  WHERE s.id = p_season_id;

  WITH club_month AS (
    SELECT
      x.club_short_name,
      count(*)::smallint AS played,
      count(*) FILTER (WHERE x.pts = 3)::smallint AS won,
      count(*) FILTER (WHERE x.pts = 1)::smallint AS drawn,
      count(*) FILTER (WHERE x.pts = 0)::smallint AS lost,
      coalesce(sum(x.gf), 0)::smallint AS gf,
      coalesce(sum(x.ga), 0)::smallint AS ga,
      coalesce(sum(x.pts), 0)::smallint AS pts
    FROM (
      SELECT
        f.home_club_short_name AS club_short_name,
        coalesce(f.home_goals, 0) AS gf,
        coalesce(f.away_goals, 0) AS ga,
        CASE
          WHEN f.home_goals > f.away_goals THEN 3
          WHEN f.home_goals = f.away_goals THEN 1
          ELSE 0
        END AS pts
      FROM public.competition_fixtures f
      WHERE f.season_id = p_season_id
        AND f.gpsl_month = v_month
        AND f.competition_type = 'league'
        AND f.status = 'played'
        AND f.home_goals IS NOT NULL
        AND f.away_goals IS NOT NULL
      UNION ALL
      SELECT
        f.away_club_short_name,
        coalesce(f.away_goals, 0),
        coalesce(f.home_goals, 0),
        CASE
          WHEN f.away_goals > f.home_goals THEN 3
          WHEN f.away_goals = f.home_goals THEN 1
          ELSE 0
        END
      FROM public.competition_fixtures f
      WHERE f.season_id = p_season_id
        AND f.gpsl_month = v_month
        AND f.competition_type = 'league'
        AND f.status = 'played'
        AND f.home_goals IS NOT NULL
        AND f.away_goals IS NOT NULL
    ) x
    GROUP BY x.club_short_name
    HAVING count(*) > 0
  )
  SELECT *
  INTO v_best
  FROM club_month cm
  ORDER BY cm.pts DESC, (cm.gf - cm.ga) DESC, cm.gf DESC, cm.club_short_name
  LIMIT 1;

  IF v_best.club_short_name IS NULL THEN
    v_motm := jsonb_build_object('ok', false, 'reason', 'no_fixtures');
  ELSE
    SELECT c.manager_id, m.name
    INTO v_manager_id, v_manager_name
    FROM public."Clubs" c
    LEFT JOIN public."Managers" m ON m.id = c.manager_id
    WHERE c."ShortName" = v_best.club_short_name;

    IF v_manager_id IS NULL THEN
      v_motm := jsonb_build_object(
        'ok', false,
        'reason', 'no_manager',
        'club_short_name', v_best.club_short_name,
        'pts', v_best.pts
      );
    ELSE
      INSERT INTO public.competition_manager_month_award (
        season_id, season_label, gpsl_month,
        manager_id, manager_name, club_short_name,
        played, won, drawn, lost, gf, ga, pts, detail
      )
      VALUES (
        p_season_id,
        coalesce(v_season_label, 'Season'),
        v_month,
        v_manager_id,
        coalesce(v_manager_name, 'Manager'),
        v_best.club_short_name,
        v_best.played,
        v_best.won,
        v_best.drawn,
        v_best.lost,
        v_best.gf,
        v_best.ga,
        v_best.pts,
        jsonb_build_object('gd', v_best.gf - v_best.ga)
      )
      ON CONFLICT (season_id, gpsl_month) DO UPDATE SET
        manager_id = EXCLUDED.manager_id,
        manager_name = EXCLUDED.manager_name,
        club_short_name = EXCLUDED.club_short_name,
        played = EXCLUDED.played,
        won = EXCLUDED.won,
        drawn = EXCLUDED.drawn,
        lost = EXCLUDED.lost,
        gf = EXCLUDED.gf,
        ga = EXCLUDED.ga,
        pts = EXCLUDED.pts,
        detail = EXCLUDED.detail,
        season_label = EXCLUDED.season_label;

      v_motm := jsonb_build_object(
        'ok', true,
        'gpsl_month', v_month,
        'manager_id', v_manager_id,
        'manager_name', v_manager_name,
        'club_short_name', v_best.club_short_name,
        'pts', v_best.pts,
        'record', format('%s-%s-%s', v_best.won, v_best.drawn, v_best.lost)
      );
    END IF;
  END IF;

  BEGIN
    v_ootm := public.competition_award_owners_of_month(p_season_id, v_month);
  EXCEPTION
    WHEN OTHERS THEN
      v_ootm := jsonb_build_object('ok', false, 'error', SQLERRM);
  END;

  RETURN v_motm || jsonb_build_object('owner_of_month', v_ootm);
END;
$function$;

GRANT EXECUTE ON FUNCTION public.competition_compute_manager_of_month(bigint, text)
  TO authenticated;

