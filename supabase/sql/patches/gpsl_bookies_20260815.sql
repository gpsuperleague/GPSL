CREATE TABLE IF NOT EXISTS public.bookies_markets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.competition_seasons (id) ON DELETE CASCADE,
  market_code text NOT NULL,
  title text NOT NULL,
  market_kind text NOT NULL CHECK (market_kind IN ('club', 'player')),
  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'closed', 'settled', 'void')),
  result_selection_key text,
  opens_at timestamptz NOT NULL DEFAULT now(),
  closes_at timestamptz,
  settled_at timestamptz,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bookies_markets_season_code UNIQUE (season_id, market_code)
);

CREATE TABLE IF NOT EXISTS public.bookies_selections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_id bigint NOT NULL REFERENCES public.bookies_markets (id) ON DELETE CASCADE,
  selection_key text NOT NULL,
  label text NOT NULL,
  odds_decimal numeric(10, 2) NOT NULL CHECK (odds_decimal >= 1.01),
  sort_order int NOT NULL DEFAULT 0,
  weight numeric NOT NULL DEFAULT 1,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bookies_selections_market_key UNIQUE (market_id, selection_key)
);

CREATE TABLE IF NOT EXISTS public.bookies_bets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.competition_seasons (id) ON DELETE CASCADE,
  market_id bigint NOT NULL REFERENCES public.bookies_markets (id) ON DELETE CASCADE,
  selection_id bigint NOT NULL REFERENCES public.bookies_selections (id) ON DELETE RESTRICT,
  owner_id uuid NOT NULL,
  club_short_name text NOT NULL,
  stake numeric(12, 2) NOT NULL CHECK (stake > 0 AND stake <= 1000),
  odds_decimal numeric(10, 2) NOT NULL,
  potential_return numeric(14, 2) NOT NULL,
  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'won', 'lost', 'void', 'refunded')),
  placed_at timestamptz NOT NULL DEFAULT now(),
  settled_at timestamptz,
  ledger_stake_id bigint,
  ledger_payout_id bigint,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT bookies_bets_once_per_option UNIQUE (owner_id, market_id, selection_id)
);

CREATE INDEX IF NOT EXISTS bookies_markets_season_status_idx
