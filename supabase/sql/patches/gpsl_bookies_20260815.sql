-- =============================================================================
-- GPSL Bookies (play-money only)
--
-- Rules:
--   窶｢ Max stake 竄ｿ1,000 per bet
--   窶｢ One bet per owner per selection (market option)
--   窶｢ Team odds: owner rank if available, else club prestige rank
--   窶｢ Player odds: in-game stats (club-contracted players only)
--
-- Ledger:
--   bookies_expenditure  窶・stake (negative)
--   bookies_income       窶・winnings (positive)
--   Descriptions name the individual bet
--
-- Safe re-run.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Ledger entry types
-- ---------------------------------------------------------------------------
DO $ledger_types$
DECLARE
  v_list text;
BEGIN
  SELECT string_agg(quote_literal(t), ', ' ORDER BY t)
  INTO v_list
  FROM (
    SELECT DISTINCT entry_type AS t
    FROM public.competition_finance_ledger
    WHERE entry_type IS NOT NULL
    UNION
    SELECT unnest(ARRAY[
      'bookies_expenditure',
      'bookies_income'
    ])
  ) s;

  ALTER TABLE public.competition_finance_ledger
    DROP CONSTRAINT IF EXISTS competition_finance_ledger_entry_type_check;

  EXECUTE format(
    'ALTER TABLE public.competition_finance_ledger
       ADD CONSTRAINT competition_finance_ledger_entry_type_check
       CHECK (entry_type IN (%s))',
    v_list
  );
END;
$ledger_types$;

