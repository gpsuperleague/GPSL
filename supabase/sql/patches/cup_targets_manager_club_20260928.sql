-- =============================================================================
-- Cup targets: alternative route for manager targets + club season expectations
--
-- A cup target only rescues a SLIGHT league miss:
--   • Club: performance band 'slight' + any club cup target met → on target
--     (no board fine / forced listing; counts as met for manager deal rules).
--     'bad' / 'abysmal' are never rescued. Stadium fill is unchanged (league only).
--   • Manager: league target missed by ≤ manager_cup_rescue_places (default 2)
--     places, not relegated, and the rule's cup target met → counts as a hit.
--     avoid_relegation misses are never rescued.
--
-- Cups: league_cup, super8, plate, shield, bowl. Stages: r16, qf, sf, final, win
-- (counted back from the final, so they work whatever the bracket size).
-- A cup target is ignored if that cup wasn't drawn this season or the club
-- wasn't in it (e.g. Super8 not qualified, Plate/Shield/Bowl off).
--
-- Club cup targets are set by prestige rank on Admin → Club attendance & prestige.
-- Manager cup targets are set per rule on Admin → Manager contract targets.
--
-- Run after season_expectation_outcomes_refine_20260924.sql. Safe re-run.
-- =============================================================================

ALTER TABLE public.global_settings
  ADD COLUMN IF NOT EXISTS manager_cup_rescue_places smallint NOT NULL DEFAULT 2;

-- ---------------------------------------------------------------------------
-- Manager rule: optional cup target
-- ---------------------------------------------------------------------------
ALTER TABLE public.manager_rating_targets
  ADD COLUMN IF NOT EXISTS cup_code text,
  ADD COLUMN IF NOT EXISTS cup_stage text;

ALTER TABLE public.manager_rating_targets
  DROP CONSTRAINT IF EXISTS manager_rating_targets_cup_check;
ALTER TABLE public.manager_rating_targets
  ADD CONSTRAINT manager_rating_targets_cup_check CHECK (
    (cup_code IS NULL AND cup_stage IS NULL)
    OR (
      cup_code IN ('league_cup', 'super8', 'plate', 'shield', 'bowl')
      AND cup_stage IN ('r16', 'qf', 'sf', 'final', 'win')
    )
  );

-- ---------------------------------------------------------------------------
-- Club cup targets by prestige rank
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.club_prestige_cup_targets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  min_rank smallint NOT NULL CHECK (min_rank >= 1),
  max_rank smallint NOT NULL,
  cup_code text NOT NULL CHECK (cup_code IN ('league_cup', 'super8', 'plate', 'shield', 'bowl')),
  cup_stage text NOT NULL CHECK (cup_stage IN ('r16', 'qf', 'sf', 'final', 'win')),
  label text,
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT club_prestige_cup_targets_rank_check CHECK (max_rank >= min_rank)
);

ALTER TABLE public.club_prestige_cup_targets ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS club_prestige_cup_targets_select ON public.club_prestige_cup_targets;
CREATE POLICY club_prestige_cup_targets_select
  ON public.club_prestige_cup_targets FOR SELECT TO authenticated USING (true);

-- ---------------------------------------------------------------------------
-- Helpers
