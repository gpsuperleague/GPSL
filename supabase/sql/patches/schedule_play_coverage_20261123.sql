CREATE OR REPLACE FUNCTION public.fixture_play_report_state(p_fixture_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $gpsl$
DECLARE
  v_fixture public.competition_fixtures;
  v_club text;
  v_opp text;
  v_kickoff timestamptz;
  v_block_ended boolean := false;
  v_mine public.competition_fixture_play_reports;
  v_can boolean := false;
  v_reason text := NULL;
BEGIN
  SELECT * INTO v_fixture FROM public.competition_fixtures WHERE id = p_fixture_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('available', false, 'reason', 'not_found');
  END IF;

  BEGIN
    v_club := upper(nullif(btrim(public.my_club_shortname()), ''));
  EXCEPTION WHEN OTHERS THEN
    v_club := NULL;
  END;

  IF v_club IS NULL
     OR v_club NOT IN (
       upper(v_fixture.home_club_short_name),
       upper(v_fixture.away_club_short_name)
     )
  THEN
    RETURN jsonb_build_object('available', false, 'reason', 'not_in_fixture');
  END IF;

  v_opp := CASE
    WHEN v_club = upper(v_fixture.home_club_short_name) THEN v_fixture.away_club_short_name
    ELSE v_fixture.home_club_short_name
  END;

  v_kickoff := public.match_schedule_agreed_kickoff(p_fixture_id);

  SELECT * INTO v_mine
  FROM public.competition_fixture_play_reports r
  WHERE r.fixture_id = p_fixture_id
    AND upper(r.reporter_club) = v_club
    AND r.kickoff_at = v_kickoff
    AND r.status IN ('open', 'upheld')
  ORDER BY r.id DESC
  LIMIT 1;

  IF v_fixture.status <> 'scheduled' THEN
    v_reason := 'not_open';
  ELSIF to_regprocedure('public.fixture_is_manual_black_box(bigint)') IS NOT NULL
        AND public.fixture_is_manual_black_box(p_fixture_id) THEN
    v_reason := 'manual';
  ELSIF v_kickoff IS NULL THEN
    v_reason := 'no_kickoff';
  ELSE
    v_block_ended := now() >= v_kickoff
      + (public.match_schedule_block_minutes() || ' minutes')::interval;
    IF NOT v_block_ended THEN
      v_reason := 'play_window';
    ELSIF v_mine.id IS NOT NULL THEN
      v_reason := 'already_filed';
    ELSE
      v_can := true;
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'available', true,
    'can_report', v_can,
    'reason', v_reason,
    'kickoff_at', v_kickoff,
    'my_report', CASE
      WHEN v_mine.id IS NULL THEN NULL
      ELSE jsonb_build_object(
        'id', v_mine.id,
        'kind', v_mine.kind,
        'status', v_mine.status,
        'match_played', v_mine.match_played,
        'video_url', v_mine.video_url
      )
    END
  );
END;
$gpsl$;

CREATE OR REPLACE FUNCTION public.fixture_play_report_file(
  p_fixture_id bigint,
  p_match_played boolean,
  p_video_url text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $gpsl$
DECLARE
  v_state jsonb;
  v_fixture public.competition_fixtures;
  v_club text;
  v_opp text;
  v_kickoff timestamptz;
  v_url text;
  v_id bigint;
  v_href text;
  v_fmt text;
  v_played boolean := coalesce(p_match_played, false);
BEGIN
  v_state := public.fixture_play_report_state(p_fixture_id);
  IF coalesce((v_state->>'can_report')::boolean, false) = false THEN
    RAISE EXCEPTION 'A no-show report is not open on this fixture right now';
