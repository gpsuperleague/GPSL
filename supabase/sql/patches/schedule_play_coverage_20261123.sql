CREATE OR REPLACE FUNCTION public.admin_play_report_decide(
  p_id bigint,
  p_uphold boolean,
  p_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $gpsl$
DECLARE
  v_row public.competition_fixture_play_reports;
  v_fixture public.competition_fixtures;
  v_new boolean := false;
  v_already boolean := false;
  v_href text;
  v_fmt text;
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;

  SELECT * INTO v_row
  FROM public.competition_fixture_play_reports
  WHERE id = p_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Report not found';
  END IF;
  IF v_row.status <> 'open' THEN
    RAISE EXCEPTION 'That report is already decided';
  END IF;

  SELECT * INTO v_fixture FROM public.competition_fixtures WHERE id = v_row.fixture_id;
  v_href := 'fixture_schedule.html?fixture=' || v_row.fixture_id::text;
  v_fmt := public.match_schedule_format_kickoff_uk(v_row.kickoff_at);

  IF coalesce(p_uphold, false) THEN
    v_already := EXISTS (
      SELECT 1
      FROM public.competition_fixture_no_show_events e
      WHERE e.fixture_id = v_row.fixture_id
        AND e.club_short_name = v_row.accused_club
        AND e.kickoff_at = v_row.kickoff_at
    );
    IF NOT v_already THEN
      v_new := public.match_schedule_apply_reported_strike(
        v_row.fixture_id, v_row.accused_club, v_row.kickoff_at
      );
    END IF;

    UPDATE public.competition_fixture_play_reports
    SET
      status = 'upheld',
      admin_note = nullif(btrim(p_note), ''),
      decided_at = now(),
      updated_at = now()
    WHERE id = p_id;

    BEGIN
      PERFORM public.owner_inbox_send(
        'match_noshow_fine',
        'Check-in report upheld — ₿500k',
        CASE
          WHEN v_already THEN
            'Admin upheld the no-show report for ' || v_fmt
            || '. That kick-off was already fined, so no second strike.'
          ELSE
            'Admin upheld the no-show report for ' || v_fmt
            || '. ₿500k and a season strike.'
        END,
        v_row.accused_club,
        NULL, v_row.fixture_id, NULL, NULL, NULL, v_href,
        'playreport-upheld:' || p_id::text || ':accused',
        v_fixture.gpsl_month, v_fixture.season_id, NULL
      );
      PERFORM public.owner_inbox_send(
        'match_noshow_fine',
        'Check-in report upheld',
        CASE
          WHEN v_already THEN
            'Admin upheld your no-show report for ' || v_fmt
            || '. That kick-off was already fined, so no second strike.'
          ELSE
            'Admin upheld your no-show report for ' || v_fmt
            || '. The other club has the ₿500k strike.'
        END,
        v_row.reporter_club,
        NULL, v_row.fixture_id, NULL, NULL, NULL, v_href,
        'playreport-upheld:' || p_id::text || ':reporter',
        v_fixture.gpsl_month, v_fixture.season_id, NULL
      );
    EXCEPTION WHEN OTHERS THEN
      NULL;
    END;

    RETURN jsonb_build_object(
      'ok', true,
      'status', 'upheld',
      'strike_new', v_new,
      'already_fined', v_already
    );
  END IF;

  UPDATE public.competition_fixture_play_reports
  SET
    status = 'dismissed',
    admin_note = nullif(btrim(p_note), ''),
    decided_at = now(),
    updated_at = now()
  WHERE id = p_id;

  BEGIN
    PERFORM public.owner_inbox_send(
      'match_noshow_fine',
      'Check-in report dismissed',
      'Admin dismissed the check-in report for ' || v_fmt || '. No strike from that report.',
      v_row.reporter_club,
      NULL, v_row.fixture_id, NULL, NULL, NULL, v_href,
      'playreport-dismiss:' || p_id::text || ':reporter',
      v_fixture.gpsl_month, v_fixture.season_id, NULL
    );
    PERFORM public.owner_inbox_send(
      'match_noshow_fine',
      'Check-in report dismissed',
      'Admin dismissed the check-in report for ' || v_fmt || '. No strike.',
      v_row.accused_club,
      NULL, v_row.fixture_id, NULL, NULL, NULL, v_href,
      'playreport-dismiss:' || p_id::text || ':accused',
      v_fixture.gpsl_month, v_fixture.season_id, NULL
    );
  EXCEPTION WHEN OTHERS THEN
    NULL;
  END;

  RETURN jsonb_build_object('ok', true, 'status', 'dismissed');
END;
$gpsl$;

CREATE OR REPLACE FUNCTION public.admin_play_coverage_queue(p_status text DEFAULT 'open')
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $gpsl$
DECLARE
  v_status text := lower(btrim(coalesce(p_status, 'open')));
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;

  RETURN jsonb_build_object(
    'reports', COALESCE((
      SELECT jsonb_agg(row_to_json(q)::jsonb ORDER BY q.created_at DESC)
      FROM (
        SELECT
          r.id,
          r.fixture_id,
          r.kickoff_at,
          r.reporter_club,
          r.accused_club,
          r.kind,
          r.match_played,
          r.video_url,
          r.status,
          r.admin_note,
          r.created_at,
          r.decided_at,
          f.gpsl_month,
          f.competition_type,
          f.division,
          f.cup_code,
          f.matchday,
          public.club_display_name(r.reporter_club) AS reporter_name,
          public.club_display_name(r.accused_club) AS accused_name
        FROM public.competition_fixture_play_reports r
        JOIN public.competition_fixtures f ON f.id = r.fixture_id
        WHERE v_status = 'all'
           OR (v_status = 'open' AND r.status = 'open')
           OR (v_status = 'decided' AND r.status IN ('upheld', 'dismissed'))
        ORDER BY r.created_at DESC
        LIMIT 80
      ) q
    ), '[]'::jsonb),
    'already_played', COALESCE((
      SELECT jsonb_agg(row_to_json(a)::jsonb ORDER BY a.completed_at DESC)
      FROM (
        SELECT
          p.fixture_id,
          p.video_url,
          p.filed_by_club,
          p.completed_at,
          p.status,
          f.home_club_short_name,
          f.away_club_short_name,
          f.gpsl_month,
          f.competition_type,
          f.division,
          f.cup_code,
          f.matchday,
          public.club_display_name(p.filed_by_club) AS filed_by_name,
          public.club_display_name(f.home_club_short_name) AS home_name,
          public.club_display_name(f.away_club_short_name) AS away_name
        FROM public.competition_fixture_already_played p
        JOIN public.competition_fixtures f ON f.id = p.fixture_id
        WHERE p.status = 'completed'
          AND p.video_url IS NOT NULL
        ORDER BY p.completed_at DESC NULLS LAST
        LIMIT 30
      ) a
    ), '[]'::jsonb)
  );
END;
