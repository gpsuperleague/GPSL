  IF v_played THEN
    IF v_url IS NULL OR NOT public.match_video_url_allowed(v_url) THEN
      RAISE EXCEPTION 'Match video link must be https YouTube, MEGA, or a Discord video attachment';
    END IF;
  ELSE
    v_url := NULL;
  END IF;

  SELECT * INTO v_fixture FROM public.competition_fixtures WHERE id = p_fixture_id FOR UPDATE;
  v_club := upper(nullif(btrim(public.my_club_shortname()), ''));
