-- =============================================================================
-- Pub quiz: 5 rounds × 10 questions, Discord #pub quiz, Building Society prizes.
-- Text rounds 5s. Picture and song rounds 8s. Leaderboard 10s between questions,
-- 60s between rounds.
-- Prizes: 5000 / 3500 / 2000 / 1000 for anyone else who answered at least once.
-- Tied scores share the place and each is paid that place's amount.
-- Safe re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.gpsl_pub_quiz (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL DEFAULT 'Pub quiz',
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'scheduled', 'live', 'finished', 'cancelled')),
  starts_at timestamptz,
  channel_id text,
  header_message_id text,
  board_message_id text,
  question_message_id text,
  countdown_message_id text,
  phase text NOT NULL DEFAULT 'idle'
    CHECK (phase IN ('idle', 'countdown', 'question', 'board', 'break', 'done')),
  resume_at timestamptz,
  current_question_id bigint,
  current_round_no int,
  last_reveal text,
  runner_busy_until timestamptz,
  prizes_paid_at timestamptz,
  prize_1 numeric(14, 2) NOT NULL DEFAULT 5000,
  prize_2 numeric(14, 2) NOT NULL DEFAULT 3500,
  prize_3 numeric(14, 2) NOT NULL DEFAULT 2000,
  prize_rest numeric(14, 2) NOT NULL DEFAULT 1000,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gpsl_pub_quiz_round (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id bigint NOT NULL REFERENCES public.gpsl_pub_quiz (id) ON DELETE CASCADE,
  round_no int NOT NULL CHECK (round_no BETWEEN 1 AND 5),
  title text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('text', 'picture', 'song')),
  answer_seconds int NOT NULL CHECK (answer_seconds BETWEEN 3 AND 30),
  UNIQUE (quiz_id, round_no)
);

CREATE TABLE IF NOT EXISTS public.gpsl_pub_quiz_question (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id bigint NOT NULL REFERENCES public.gpsl_pub_quiz_round (id) ON DELETE CASCADE,
  q_no int NOT NULL CHECK (q_no BETWEEN 1 AND 10),
  prompt text NOT NULL DEFAULT '',
  option_a text NOT NULL DEFAULT '',
  option_b text NOT NULL DEFAULT '',
  option_c text NOT NULL DEFAULT '',
  correct char(1) NOT NULL DEFAULT 'a' CHECK (correct IN ('a', 'b', 'c')),
  media_path text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'live', 'closed')),
  opens_at timestamptz,
  closes_at timestamptz,
  UNIQUE (round_id, q_no)
);

CREATE TABLE IF NOT EXISTS public.gpsl_pub_quiz_answer (
  question_id bigint NOT NULL REFERENCES public.gpsl_pub_quiz_question (id) ON DELETE CASCADE,
  owner_id uuid NOT NULL,
  owner_tag text,
  discord_user_id text NOT NULL,
  choice char(1) NOT NULL CHECK (choice IN ('a', 'b', 'c')),
  answered_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (question_id, owner_id)
);

