CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_save_question(
  p_question_id bigint,
  p_prompt text,
  p_a text,
  p_b text,
  p_c text,
  p_correct text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_status text;
  v_correct char(1);
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  v_correct := lower(left(btrim(coalesce(p_correct, 'a')), 1))::char(1);
  IF v_correct NOT IN ('a', 'b', 'c') THEN
    RAISE EXCEPTION 'Correct answer must be a, b, or c';
  END IF;
  SELECT z.status INTO v_status
  FROM public.gpsl_pub_quiz_question qq
  JOIN public.gpsl_pub_quiz_round r ON r.id = qq.round_id
  JOIN public.gpsl_pub_quiz z ON z.id = r.quiz_id
  WHERE qq.id = p_question_id;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'Question not found';
  END IF;
  IF v_status NOT IN ('draft', 'scheduled') THEN
    RAISE EXCEPTION 'This quiz has already started';
  END IF;
  UPDATE public.gpsl_pub_quiz_question
  SET prompt = left(btrim(coalesce(p_prompt, '')), 180),
      option_a = left(btrim(coalesce(p_a, '')), 40),
      option_b = left(btrim(coalesce(p_b, '')), 40),
      option_c = left(btrim(coalesce(p_c, '')), 40),
      correct = v_correct
  WHERE id = p_question_id;
  RETURN jsonb_build_object('ok', true);
END;
$function$;

