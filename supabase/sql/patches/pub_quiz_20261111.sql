CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_pay(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_q public.gpsl_pub_quiz%rowtype;
  v_row record;
  v_amount numeric(14, 2);
  v_label text;
  v_paid int := 0;
BEGIN
  SELECT * INTO v_q FROM public.gpsl_pub_quiz WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_found');
  END IF;
  IF v_q.prizes_paid_at IS NOT NULL THEN
    RETURN jsonb_build_object('ok', true, 'already', true, 'rows', public.gpsl_pub_quiz_standings(p_id));
  END IF;

  FOR v_row IN
    SELECT * FROM jsonb_to_recordset(public.gpsl_pub_quiz_standings(p_id)) AS x(
      owner_id uuid, owner_tag text, points int, answers int, place int
    )
  LOOP
    v_amount := CASE v_row.place
      WHEN 1 THEN v_q.prize_1
      WHEN 2 THEN v_q.prize_2
      WHEN 3 THEN v_q.prize_3
      ELSE v_q.prize_rest
    END;
    v_label := CASE v_row.place
      WHEN 1 THEN '1st'
      WHEN 2 THEN '2nd'
      WHEN 3 THEN '3rd'
      ELSE 'entry'
    END;
    IF coalesce(v_amount, 0) > 0 AND coalesce(v_row.answers, 0) > 0 THEN
      PERFORM public.owner_wallet_ensure(v_row.owner_id);
      PERFORM public._post_owner_ledger_internal(
        v_row.owner_id,
        'prize',
        v_amount,
        format('Pub quiz — %s', v_label),
        jsonb_build_object('source', 'pub_quiz', 'quiz_id', p_id, 'place', v_row.place),
        NULL,
        true
      );
      v_paid := v_paid + 1;
    END IF;
  END LOOP;

  UPDATE public.gpsl_pub_quiz
  SET status = 'finished',
      phase = 'done',
      prizes_paid_at = now(),
      board_message_id = NULL,
      question_message_id = NULL,
      updated_at = now()
  WHERE id = p_id;

  RETURN jsonb_build_object(
    'ok', true,
    'paid', v_paid,
    'rows', public.gpsl_pub_quiz_standings(p_id),
    'prize_1', v_q.prize_1,
    'prize_2', v_q.prize_2,
    'prize_3', v_q.prize_3,
    'prize_rest', v_q.prize_rest
  );
END;
$function$;

