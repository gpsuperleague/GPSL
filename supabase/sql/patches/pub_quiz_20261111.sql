$$;

CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_schedule(
  p_id bigint,
  p_starts_at timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_missing int;
  v_status text;
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  IF p_starts_at IS NULL THEN
    RAISE EXCEPTION 'Pick a start time';
  END IF;
  SELECT status INTO v_status FROM public.gpsl_pub_quiz WHERE id = p_id;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'Quiz not found';
  END IF;
  IF v_status NOT IN ('draft', 'scheduled') THEN
    RAISE EXCEPTION 'This quiz has already started';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.gpsl_pub_quiz
    WHERE status IN ('scheduled', 'live') AND id <> p_id
  ) THEN
    RAISE EXCEPTION 'Another quiz is already scheduled or live';
  END IF;
  v_missing := public.gpsl_pub_quiz_missing(p_id);
  IF v_missing > 0 THEN
    RAISE EXCEPTION '% question(s) still need a prompt, three answers, or a file', v_missing;
  END IF;
  UPDATE public.gpsl_pub_quiz
  SET status = 'scheduled',
      starts_at = p_starts_at,
      phase = 'idle',
      updated_at = now()
  WHERE id = p_id;
  RETURN jsonb_build_object('ok', true, 'missing', 0);
END;
$function$;

