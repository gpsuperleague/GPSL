CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_close_question(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_q public.gpsl_pub_quiz%rowtype;
  v_qq public.gpsl_pub_quiz_question%rowtype;
  v_round public.gpsl_pub_quiz_round%rowtype;
  v_answer text;
  v_more_in_round boolean;
  v_more_rounds boolean;
  v_gap int;
BEGIN
  SELECT * INTO v_q FROM public.gpsl_pub_quiz WHERE id = p_id FOR UPDATE;
  IF NOT FOUND OR v_q.current_question_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'no_question');
  END IF;
  SELECT * INTO v_qq FROM public.gpsl_pub_quiz_question WHERE id = v_q.current_question_id;
  SELECT * INTO v_round FROM public.gpsl_pub_quiz_round WHERE id = v_qq.round_id;

  UPDATE public.gpsl_pub_quiz_question SET status = 'closed' WHERE id = v_qq.id AND status = 'live';

  v_answer := CASE v_qq.correct
    WHEN 'a' THEN v_qq.option_a
    WHEN 'b' THEN v_qq.option_b
    ELSE v_qq.option_c
  END;

  SELECT EXISTS (
    SELECT 1 FROM public.gpsl_pub_quiz_question qq
    WHERE qq.round_id = v_round.id AND qq.status = 'pending'
  ) INTO v_more_in_round;

  SELECT EXISTS (
    SELECT 1
    FROM public.gpsl_pub_quiz_question qq
    JOIN public.gpsl_pub_quiz_round r ON r.id = qq.round_id
    WHERE r.quiz_id = p_id AND r.round_no > v_round.round_no AND qq.status = 'pending'
  ) INTO v_more_rounds;

  v_gap := CASE
    WHEN v_more_in_round THEN 10
    WHEN v_more_rounds THEN 60
    ELSE 10
  END;

  UPDATE public.gpsl_pub_quiz
  SET phase = CASE WHEN v_more_in_round THEN 'board' ELSE 'break' END,
      resume_at = now() + make_interval(secs => v_gap),
      last_reveal = format('%s · %s', upper(v_qq.correct::text), v_answer),
      question_message_id = NULL,
      updated_at = now()
  WHERE id = p_id;

  RETURN jsonb_build_object(
    'ok', true,
    'question_message_id', v_q.question_message_id,
    'channel_id', v_q.channel_id,
    'reveal', format('%s · %s', upper(v_qq.correct::text), v_answer),
    'round_no', v_round.round_no,
    'round_title', v_round.title,
    'q_no', v_qq.q_no,
    'more_in_round', v_more_in_round,
    'more_rounds', v_more_rounds,
    'finish_after', (NOT v_more_in_round AND NOT v_more_rounds),
    'gap_seconds', v_gap,
    'resume_at', now() + make_interval(secs => v_gap),
    'rows', public.gpsl_pub_quiz_standings(p_id)
  );
END;
$function$;

