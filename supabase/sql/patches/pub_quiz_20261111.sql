      WHERE qq.round_id = r.id
    )
  ) ORDER BY r.round_no), '[]'::jsonb)
  INTO v_rounds
  FROM public.gpsl_pub_quiz_round r
  WHERE r.quiz_id = p_id;
  RETURN jsonb_build_object('ok', true, 'quiz', v_quiz, 'rounds', v_rounds);
