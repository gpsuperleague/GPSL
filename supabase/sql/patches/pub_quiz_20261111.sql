CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_request()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, net
AS $function$
DECLARE
  v_url text;
  v_key text;
  v_enabled boolean;
BEGIN
  SELECT s.edge_function_url, s.invoke_key, s.auto_poll_enabled
  INTO v_url, v_key, v_enabled
  FROM public.gpsl_pub_quiz_settings s
  WHERE s.id = 1;
  IF NOT coalesce(v_enabled, false) THEN
    RETURN;
  END IF;
  IF v_url IS NULL OR btrim(v_url) = '' OR v_key IS NULL OR btrim(v_key) = '' THEN
    RETURN;
  END IF;
  PERFORM net.http_post(
    url := v_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || v_key
    ),
    body := jsonb_build_object('action', 'kick'),
    timeout_milliseconds := 8000
  );
  UPDATE public.gpsl_pub_quiz_settings
  SET last_run_at = now(), updated_at = now()
  WHERE id = 1;
EXCEPTION
  WHEN undefined_function THEN
    RAISE WARNING 'gpsl_pub_quiz_request: pg_net missing';
  WHEN OTHERS THEN
    RAISE WARNING 'gpsl_pub_quiz_request failed: %', SQLERRM;
END;
$function$;

