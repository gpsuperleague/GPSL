CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_missing(p_id bigint)
RETURNS int
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT count(*)::int
  FROM public.gpsl_pub_quiz_question qq
  JOIN public.gpsl_pub_quiz_round r ON r.id = qq.round_id
  WHERE r.quiz_id = p_id
    AND (
      btrim(qq.prompt) = ''
      OR btrim(qq.option_a) = ''
      OR btrim(qq.option_b) = ''
      OR btrim(qq.option_c) = ''
      OR (r.kind IN ('picture', 'song') AND nullif(btrim(coalesce(qq.media_path, '')), '') IS NULL)
