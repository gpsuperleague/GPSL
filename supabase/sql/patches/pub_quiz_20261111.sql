CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_open_question(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_q public.gpsl_pub_quiz%rowtype;
  v_row record;
  v_closes timestamptz;
BEGIN
  SELECT * INTO v_q FROM public.gpsl_pub_quiz WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_found');
  END IF;

  SELECT qq.*, r.round_no, r.title AS round_title, r.kind, r.answer_seconds
  INTO v_row
  FROM public.gpsl_pub_quiz_question qq
  JOIN public.gpsl_pub_quiz_round r ON r.id = qq.round_id
  WHERE r.quiz_id = p_id
    AND qq.status = 'pending'
  ORDER BY r.round_no, qq.q_no
  LIMIT 1;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', true, 'done', true);
  END IF;

  v_closes := now() + make_interval(secs => v_row.answer_seconds);
  UPDATE public.gpsl_pub_quiz_question
  SET status = 'live', opens_at = now(), closes_at = v_closes
  WHERE id = v_row.id;

  UPDATE public.gpsl_pub_quiz
  SET status = 'live',
      phase = 'question',
      current_question_id = v_row.id,
      current_round_no = v_row.round_no,
      question_message_id = NULL,
      updated_at = now()
  WHERE id = p_id;

  RETURN jsonb_build_object(
    'ok', true,
    'done', false,
    'question_id', v_row.id,
    'round_no', v_row.round_no,
    'round_title', v_row.round_title,
    'kind', v_row.kind,
    'q_no', v_row.q_no,
    'prompt', v_row.prompt,
    'option_a', v_row.option_a,
    'option_b', v_row.option_b,
    'option_c', v_row.option_c,
    'media_path', v_row.media_path,
    'answer_seconds', v_row.answer_seconds,
    'closes_at', v_closes
  );
END;
$function$;

