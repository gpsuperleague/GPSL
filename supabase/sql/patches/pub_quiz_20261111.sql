CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_create()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_id bigint;
  v_round bigint;
  i int;
  r record;
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;

  INSERT INTO public.gpsl_pub_quiz (title)
  VALUES ('Pub quiz')
  RETURNING id INTO v_id;

  FOR r IN
    SELECT * FROM (VALUES
      (1, 'World Cup football', 'text', 5),
      (2, 'Picture round', 'picture', 8),
      (3, 'English football', 'text', 5),
      (4, 'Songs', 'song', 8),
      (5, 'General knowledge', 'text', 5)
    ) AS t(round_no, title, kind, secs)
  LOOP
    INSERT INTO public.gpsl_pub_quiz_round (quiz_id, round_no, title, kind, answer_seconds)
    VALUES (v_id, r.round_no, r.title, r.kind, r.secs)
    RETURNING id INTO v_round;
    FOR i IN 1..10 LOOP
      INSERT INTO public.gpsl_pub_quiz_question (round_id, q_no)
      VALUES (v_round, i);
    END LOOP;
  END LOOP;

  RETURN jsonb_build_object('ok', true, 'id', v_id);
END;
$function$;

