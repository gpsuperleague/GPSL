CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_standings(p_quiz_id bigint)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH scores AS (
    SELECT
      a.owner_id,
      max(a.owner_tag) AS owner_tag,
      count(*) FILTER (WHERE a.choice = q.correct)::int AS points,
      count(*)::int AS answers
    FROM public.gpsl_pub_quiz_answer a
    JOIN public.gpsl_pub_quiz_question q ON q.id = a.question_id
    JOIN public.gpsl_pub_quiz_round r ON r.id = q.round_id
    WHERE r.quiz_id = p_quiz_id
      AND q.status = 'closed'
    GROUP BY a.owner_id
  ),
  ranked AS (
    SELECT
      s.*,
      dense_rank() OVER (ORDER BY s.points DESC, s.owner_tag ASC NULLS LAST) AS place
    FROM scores s
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'owner_id', owner_id,
    'owner_tag', owner_tag,
    'points', points,
    'answers', answers,
    'place', place
  ) ORDER BY place, owner_tag), '[]'::jsonb)
  FROM ranked;
$$;

REVOKE ALL ON FUNCTION public.gpsl_pub_quiz_standings(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.gpsl_pub_quiz_standings(bigint) TO service_role;

CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_public_board(p_quiz_id bigint DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_id bigint := p_quiz_id;
  v_q public.gpsl_pub_quiz%rowtype;
BEGIN
  IF v_id IS NULL THEN
    SELECT id INTO v_id
    FROM public.gpsl_pub_quiz
    WHERE status IN ('live', 'finished', 'scheduled')
    ORDER BY CASE status WHEN 'live' THEN 0 WHEN 'scheduled' THEN 1 ELSE 2 END, id DESC
    LIMIT 1;
  END IF;
  IF v_id IS NULL THEN
    RETURN jsonb_build_object('ok', true, 'quiz', NULL, 'rows', '[]'::jsonb);
  END IF;
  SELECT * INTO v_q FROM public.gpsl_pub_quiz WHERE id = v_id;
  RETURN jsonb_build_object(
    'ok', true,
    'quiz', jsonb_build_object(
      'id', v_q.id,
      'title', v_q.title,
      'status', v_q.status,
      'phase', v_q.phase,
      'starts_at', v_q.starts_at,
      'current_round_no', v_q.current_round_no,
      'last_reveal', CASE WHEN v_q.status IN ('live', 'finished') THEN v_q.last_reveal ELSE NULL END,
      'prize_1', v_q.prize_1,
      'prize_2', v_q.prize_2,
      'prize_3', v_q.prize_3,
      'prize_rest', v_q.prize_rest,
      'prizes_paid_at', v_q.prizes_paid_at
    ),
    'rows', public.gpsl_pub_quiz_standings(v_id)
  );
END;
$function$;

GRANT EXECUTE ON FUNCTION public.gpsl_pub_quiz_public_board(bigint) TO anon, authenticated;

