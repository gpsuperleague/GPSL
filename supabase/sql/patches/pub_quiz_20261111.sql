CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_admin_get(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_quiz jsonb;
  v_rounds jsonb;
BEGIN
  IF NOT public.is_gpsl_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  SELECT to_jsonb(q) INTO v_quiz FROM public.gpsl_pub_quiz q WHERE q.id = p_id;
  IF v_quiz IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_found');
