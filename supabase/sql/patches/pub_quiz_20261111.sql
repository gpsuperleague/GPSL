CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_lock_answer(
  p_discord_user_id text,
  p_question_id bigint,
  p_choice text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_user text := nullif(btrim(coalesce(p_discord_user_id, '')), '');
  v_choice char(1);
  v_owner uuid;
  v_tag text;
  v_q public.gpsl_pub_quiz_question%rowtype;
  v_inserted int := 0;
BEGIN
  v_choice := lower(left(btrim(coalesce(p_choice, '')), 1))::char(1);
  IF v_user IS NULL OR v_choice NOT IN ('a', 'b', 'c') THEN
    RETURN jsonb_build_object('ok', false, 'message', 'That answer was not recognised.');
  END IF;

  SELECT r.owner_id, r.owner_tag INTO v_owner, v_tag
  FROM public.gpsl_owner_registry r
  WHERE r.discord_user_id = v_user
  LIMIT 1;
  IF v_owner IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'message', 'Owners only. Link your Discord account on GPSL first.');
  END IF;

  SELECT * INTO v_q FROM public.gpsl_pub_quiz_question WHERE id = p_question_id;
  IF NOT FOUND OR v_q.status <> 'live' OR v_q.closes_at IS NULL OR now() >= v_q.closes_at THEN
    RETURN jsonb_build_object('ok', false, 'message', 'Too late. That question has closed.');
  END IF;

  INSERT INTO public.gpsl_pub_quiz_answer (question_id, owner_id, owner_tag, discord_user_id, choice)
  VALUES (p_question_id, v_owner, v_tag, v_user, v_choice)
  ON CONFLICT (question_id, owner_id) DO NOTHING;
  GET DIAGNOSTICS v_inserted = ROW_COUNT;
  IF v_inserted = 0 THEN
    RETURN jsonb_build_object('ok', false, 'message', 'Already answered.');
  END IF;
  RETURN jsonb_build_object(
    'ok', true,
    'message', format('Locked in: %s', upper(v_choice::text))
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.gpsl_pub_quiz_lock_answer(text, bigint, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.gpsl_pub_quiz_lock_answer(text, bigint, text) TO service_role;

CREATE OR REPLACE FUNCTION public.gpsl_pub_quiz_runner_claim()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_id bigint;
  v_q public.gpsl_pub_quiz%rowtype;
BEGIN
  SELECT z.id INTO v_id
  FROM public.gpsl_pub_quiz z
  WHERE (
      z.status = 'scheduled'
      AND z.starts_at IS NOT NULL
      AND z.starts_at <= now() + interval '5 minutes'
    )
    OR (
      z.status = 'live'
      AND (
        (z.phase = 'question' AND z.current_question_id IS NOT NULL AND EXISTS (
          SELECT 1 FROM public.gpsl_pub_quiz_question qq
          WHERE qq.id = z.current_question_id AND qq.closes_at IS NOT NULL AND qq.closes_at <= now()
        ))
        OR (z.phase IN ('board', 'break') AND z.resume_at IS NOT NULL AND z.resume_at <= now())
        OR (z.phase = 'countdown' AND z.starts_at IS NOT NULL AND z.starts_at <= now())
      )
    )
  ORDER BY CASE z.status WHEN 'live' THEN 0 ELSE 1 END, z.id
  LIMIT 1
  FOR UPDATE SKIP LOCKED;

  IF v_id IS NULL THEN
    RETURN jsonb_build_object('ok', true, 'due', false);
  END IF;

  UPDATE public.gpsl_pub_quiz
  SET runner_busy_until = now() + interval '90 seconds',
      updated_at = now()
  WHERE id = v_id
    AND (runner_busy_until IS NULL OR runner_busy_until < now())
  RETURNING * INTO v_q;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', true, 'due', false, 'busy', true);
  END IF;

  RETURN jsonb_build_object('ok', true, 'due', true, 'quiz', to_jsonb(v_q));
END;
$function$;

