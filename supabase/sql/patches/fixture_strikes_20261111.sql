-- Fixture strikes (from the October 2026 lock onward)
--
-- Every new strike: ₿500k, and it counts on the season.
-- Every 5th, 10th, 15th… season strike: another ₿1m.
-- 3 strikes on one fixture: another ₿1m and that club forfeits.
-- League only: a month lock with no home proposal is a strike, not ₿2.5m.
--   An away proposal before the lock stops that sequence.
--   Away may send the first proposal once the month before the play month has locked.
-- Last-window award: more strikes loses; level strikes use effort; level effort is a void.
-- Cups, holidays, new-owner grace, agreed fixtures, and manual arrange are unchanged.
-- Locks already closed are not replayed into strikes.

INSERT INTO public.competition_fine_tariff (
  code, label, category, direction, amount, amount_mode, sort_order, is_active
)
VALUES
  ('match_strike', 'Strike', 'matchday', 'fine', 500000, 'fixed', 75, true),
  ('match_strike_season_fifth', 'Season strike (every 5th)', 'matchday', 'fine', 1000000, 'fixed', 76, true),
  ('match_strike_fixture_third', 'Third strike on a fixture', 'matchday', 'fine', 1000000, 'fixed', 77, true)
ON CONFLICT (code) DO UPDATE SET
  label = EXCLUDED.label,
  amount = EXCLUDED.amount,
  is_active = true,
  updated_at = now();

CREATE TABLE IF NOT EXISTS public.competition_fixture_proposal_strikes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id bigint NOT NULL REFERENCES public.competition_fixtures (id) ON DELETE CASCADE,
  club_short_name text NOT NULL,
  gpsl_month text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT competition_fixture_proposal_strikes_uniq
    UNIQUE (fixture_id, club_short_name, gpsl_month)
);

CREATE OR REPLACE FUNCTION public.match_schedule_fixture_strike_count(
  p_fixture_id bigint,
  p_club text
)
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT (
    coalesce((
      SELECT count(*)::int
      FROM public.competition_fixture_no_show_events e
      WHERE e.fixture_id = p_fixture_id
        AND e.club_short_name = p_club
    ), 0)
    + coalesce((
      SELECT count(*)::int
      FROM public.competition_fixture_proposal_strikes s
      WHERE s.fixture_id = p_fixture_id
        AND s.club_short_name = p_club
    ), 0)
  );
$$;

CREATE OR REPLACE FUNCTION public.match_schedule_add_season_strike(
  p_season_id bigint,
  p_owner_id uuid,
  p_fixture_id bigint,
  p_club_short_name text
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_count integer;
  v_href text;
BEGIN
  IF p_season_id IS NULL OR p_owner_id IS NULL THEN
    RETURN 0;
  END IF;

  INSERT INTO public.competition_owner_season_strikes (season_id, owner_id, strike_count, updated_at)
  VALUES (p_season_id, p_owner_id, 1, now())
  ON CONFLICT (season_id, owner_id) DO UPDATE
    SET strike_count = public.competition_owner_season_strikes.strike_count + 1,
        updated_at = now()
  RETURNING strike_count INTO v_count;

  IF v_count > 0 AND v_count % 5 = 0 THEN
    PERFORM public.competition_apply_club_fine_tariff(
      p_club_short_name,
      'match_strike_season_fifth',
      NULL,
      format('Season strike #%s', v_count),
      p_fixture_id,
      p_season_id
    );
    v_href := 'fixture_schedule.html?fixture=' || p_fixture_id::text;
    PERFORM public.owner_inbox_send(
      'match_noshow_strike_triple',
      'Season strike ' || v_count::text || ' — ₿1m',
      'Season strike ' || v_count::text
        || ' of the season. That strike is also ₿500k. Every 5th (5, 10, 15…) adds ₿1m.',
      p_club_short_name,
      NULL, p_fixture_id, NULL, NULL, NULL, v_href,
      'strike5:' || p_season_id::text || ':' || p_owner_id::text || ':' || v_count::text,
      NULL, p_season_id, NULL
    );
  END IF;

  RETURN v_count;
END;
$function$;

CREATE OR REPLACE FUNCTION public.match_schedule_on_strike(
  p_fixture_id bigint,
  p_club text,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_fixture public.competition_fixtures;
  v_owner uuid;
  v_season_n integer := 0;
  v_fix integer := 0;
  v_href text;
  v_note text;
BEGIN
  SELECT * INTO v_fixture FROM public.competition_fixtures WHERE id = p_fixture_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'missing');
  END IF;

  v_note := CASE
    WHEN p_reason = 'no_proposal' THEN 'No home proposal'
    ELSE 'Missed check-in'
  END;

  PERFORM public.competition_apply_club_fine_tariff(
    p_club,
    'match_strike',
    NULL,
    v_note,
    p_fixture_id,
    v_fixture.season_id
  );

  v_owner := public.match_schedule_club_owner_id(p_club);
  v_season_n := public.match_schedule_add_season_strike(
    v_fixture.season_id, v_owner, p_fixture_id, p_club
  );
  v_fix := public.match_schedule_fixture_strike_count(p_fixture_id, p_club);
  v_href := 'fixture_schedule.html?fixture=' || p_fixture_id::text;

  IF p_reason = 'no_proposal' THEN
    PERFORM public.owner_inbox_send(
      'match_noshow_fine',
      'No proposal — strike, ₿500k',
      coalesce(public.club_display_name(p_club), p_club)
        || ' has not proposed. Strike ' || v_fix::text
        || ' of 3 on this fixture. Season strikes: ' || v_season_n::text
        || '. Each strike is ₿500k. A third on this fixture forfeits it and adds ₿1m.',
      p_club,
      NULL, p_fixture_id, NULL, NULL, NULL, v_href,
      'propstrike:' || p_fixture_id::text || ':' || p_club || ':' || v_fix::text,
      v_fixture.gpsl_month, v_fixture.season_id, NULL
    );
  END IF;

  IF v_fix >= 3 AND v_fixture.status = 'scheduled' THEN
    PERFORM public.competition_apply_club_fine_tariff(
      p_club,
      'match_strike_fixture_third',
      NULL,
      'Third strike on this fixture',
      p_fixture_id,
      v_fixture.season_id
    );
    PERFORM public.fixture_apply_forfeit(
      p_fixture_id,
      p_club,
      'match_no_show_fixture_forfeit',
      'Third strike on this fixture'
    );
    PERFORM public.owner_inbox_send(
      'match_noshow_fixture_forfeit',
      'Third strike — match forfeited',
      coalesce(public.club_display_name(p_club), p_club)
        || ' reached 3 strikes on this fixture. ₿1m, and the match is forfeited.',
      v_fixture.home_club_short_name,
      NULL, p_fixture_id, NULL, NULL, NULL, v_href,
      'strike3ff:' || p_fixture_id::text || ':home:' || p_club,
      v_fixture.gpsl_month, v_fixture.season_id, NULL
    );
    PERFORM public.owner_inbox_send(
      'match_noshow_fixture_forfeit',
      'Third strike — match forfeited',
      coalesce(public.club_display_name(p_club), p_club)
        || ' reached 3 strikes on this fixture. ₿1m, and the match is forfeited.',
      v_fixture.away_club_short_name,
      NULL, p_fixture_id, NULL, NULL, NULL, v_href,
      'strike3ff:' || p_fixture_id::text || ':away:' || p_club,
      v_fixture.gpsl_month, v_fixture.season_id, NULL
    );
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'fixture_strikes', v_fix,
    'season_strikes', v_season_n,
    'forfeited', v_fix >= 3
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.match_schedule_record_proposal_strike(
  p_fixture_id bigint,
  p_club text,
  p_closed_month text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_rows integer := 0;
BEGIN
  INSERT INTO public.competition_fixture_proposal_strikes (fixture_id, club_short_name, gpsl_month)
  VALUES (p_fixture_id, p_club, lower(btrim(p_closed_month)))
  ON CONFLICT (fixture_id, club_short_name, gpsl_month) DO NOTHING;

  GET DIAGNOSTICS v_rows = ROW_COUNT;
  IF v_rows = 0 THEN
    RETURN;
  END IF;

  PERFORM public.match_schedule_on_strike(p_fixture_id, p_club, 'no_proposal');
END;
$function$;

-- No-show: ₿500k strike instead of ₿500k / ₿1m / ₿1.5m. The old 3rd-forfeit block is switched off;
-- match_schedule_on_strike forfeits at 3 combined strikes (check-ins plus proposal misses).
DO $noshow$
DECLARE
  v_def text;
  v_old text;
  v_new text;
BEGIN
  SELECT replace(pg_get_functiondef(
    'public.match_schedule_apply_club_noshow(bigint,text,timestamptz,integer,boolean)'::regprocedure
  ), E'\r\n', E'\n') INTO v_def;

  v_new := $new$
  v_tariff := 'match_strike';
  v_amount_label := '₿500k';
  PERFORM public.match_schedule_on_strike(p_fixture_id, p_club, 'noshow');
  v_n := public.match_schedule_fixture_strike_count(p_fixture_id, p_club);$new$;

  IF position('match_no_show_1' IN v_def) = 0 THEN
    RAISE EXCEPTION 'no-show tariff block not found';
  END IF;
  v_def := regexp_replace(
    v_def,
    'v_tariff := CASE\s+WHEN v_n <= 1 THEN ''match_no_show_1''\s+WHEN v_n = 2 THEN ''match_no_show_2''\s+ELSE ''match_no_show_3''\s+END;',
    v_new,
    'n'
  );
  IF position('match_no_show_1' IN v_def) > 0 THEN
    RAISE EXCEPTION 'no-show tariff block was not replaced';
  END IF;

  IF position('IF v_n >= 3 AND NOT p_both_miss THEN' IN v_def) = 0 THEN
    RAISE EXCEPTION 'no-show forfeit block not found';
  END IF;
  v_def := replace(
    v_def,
    'IF v_n >= 3 AND NOT p_both_miss THEN',
    'IF false AND v_n >= 3 AND NOT p_both_miss THEN'
  );

  -- The old ladder also charged here. on_strike already charged ₿500k and the season strike.
  v_def := regexp_replace(
    v_def,
    'PERFORM public\.competition_apply_club_fine_tariff\(\s*p_club, v_tariff, NULL,\s*format\(''Fixture no-show #%s at attempt %s'', v_n, p_attempt\),\s*p_fixture_id, v_fixture\.season_id\s*\);\s*v_owner := public\.match_schedule_club_owner_id\(p_club\);\s*v_strikes := public\.match_schedule_add_season_strike\(\s*v_fixture\.season_id, v_owner, p_fixture_id, p_club\s*\);',
    'v_owner := public.match_schedule_club_owner_id(p_club);'
      || E'\n  v_strikes := coalesce((SELECT s.strike_count FROM public.competition_owner_season_strikes s WHERE s.season_id = v_fixture.season_id AND s.owner_id = v_owner), 0);',
    'n'
  );
  IF position('match_schedule_add_season_strike(' IN v_def) > 0 THEN
    RAISE EXCEPTION 'no-show fine call not found';
  END IF;

  v_def := regexp_replace(
    v_def,
    'v_amount_label := CASE\s+WHEN v_n <= 1 THEN ''[^'']+''\s+WHEN v_n = 2 THEN ''[^'']+''\s+ELSE ''[^'']+''\s+END;',
    'v_amount_label := ''₿500k'';',
    'n'
  );

  EXECUTE v_def;
END;
$noshow$;

-- League no-proposal locks from the current October lock onward become strikes.
DO $propose_strike$
DECLARE
  v_def text;
  v_old text;
  v_new text;
  v_cut timestamptz;
BEGIN
  SELECT c.lock_at INTO v_cut
  FROM public.competition_season_calendar c
  JOIN public.competition_seasons s ON s.id = c.season_id AND s.is_current
  WHERE lower(btrim(c.gpsl_month)) = 'october'
  ORDER BY s.id DESC
  LIMIT 1;

  IF v_cut IS NULL THEN
    RAISE EXCEPTION 'October lock not found — proposal strikes NOT applied';
  END IF;

  SELECT replace(pg_get_functiondef(
    'public.competition_enforce_scheduling_arrangement_fines(bigint,text)'::regprocedure
  ), E'\r\n', E'\n') INTO v_def;

  IF position('proposal strike cutover' IN v_def) > 0 THEN
    RAISE NOTICE 'arrangement fines already record proposal strikes';
    RETURN;
  END IF;

  v_old := $old$    IF v_tariff_code IS NULL THEN$old$;
  v_new := format($new$    -- proposal strike cutover: %s
    IF v_tariff_code = 'match_mgmt_no_proposal'
       AND v_closed_lock >= %L::timestamptz
       AND lower(coalesce(v_f.competition_type, 'league')) <> 'cup'
       AND NOT (
         to_regprocedure('public.fixture_is_manual_black_box(bigint)') IS NOT NULL
         AND public.fixture_is_manual_black_box(v_f.id)
       ) THEN
      IF EXISTS (
        SELECT 1
        FROM public.competition_fixture_schedule_proposal p
        WHERE p.fixture_id = v_f.id
          AND p.proposed_by_club_short_name = v_f.away_club_short_name
          AND p.status <> 'withdrawn'
      ) THEN
        v_tariff_code := NULL;
      ELSE
        PERFORM public.match_schedule_record_proposal_strike(
          v_f.id, v_f.home_club_short_name, p_closed_gpsl_month
        );
        v_tariff_code := NULL;
      END IF;
    END IF;

    IF v_tariff_code IS NULL THEN$new$, v_cut, v_cut);

  IF position(v_old IN v_def) = 0 THEN
    RAISE EXCEPTION 'arrangement fines: tariff null check not found';
  END IF;

  EXECUTE replace(v_def, v_old, v_new);
END;
$propose_strike$;

CREATE OR REPLACE FUNCTION public.match_schedule_away_may_open_proposal(p_fixture_id bigint)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_f public.competition_fixtures;
  v_play int;
  v_lock timestamptz;
BEGIN
  SELECT * INTO v_f FROM public.competition_fixtures WHERE id = p_fixture_id;
  IF NOT FOUND OR v_f.status IS DISTINCT FROM 'scheduled' THEN
    RETURN false;
  END IF;
  IF lower(coalesce(v_f.competition_type, 'league')) = 'cup' THEN
    RETURN false;
  END IF;
  IF to_regprocedure('public.fixture_is_manual_black_box(bigint)') IS NOT NULL
     AND public.fixture_is_manual_black_box(p_fixture_id) THEN
    RETURN false;
  END IF;
  IF to_regprocedure('public.competition_fixture_involves_vacant_club(bigint)') IS NOT NULL
     AND public.competition_fixture_involves_vacant_club(p_fixture_id) THEN
    RETURN false;
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.competition_fixture_schedule_proposal p
    WHERE p.fixture_id = p_fixture_id
      AND p.proposed_by_club_short_name = v_f.home_club_short_name
      AND p.status <> 'withdrawn'
  ) THEN
    RETURN false;
  END IF;

  v_play := public.competition_gpsl_month_sort(v_f.gpsl_month);
  SELECT c.lock_at INTO v_lock
  FROM public.competition_season_calendar c
  WHERE c.season_id = v_f.season_id
    AND public.competition_gpsl_month_sort(c.gpsl_month) = v_play - 1
  ORDER BY c.lock_at
  LIMIT 1;

  RETURN v_lock IS NOT NULL AND v_lock <= now();
END;
$function$;

DO $away_open$
DECLARE
  v_def text;
  v_old text;
  v_new text;
BEGIN
  SELECT replace(pg_get_functiondef(
    'public.fixture_schedule_propose(bigint,timestamptz)'::regprocedure
  ), E'\r\n', E'\n') INTO v_def;

  IF position('match_schedule_away_may_open_proposal' IN v_def) > 0 THEN
    RAISE NOTICE 'propose already allows a late away opening';
    RETURN;
  END IF;

  IF position('match_schedule_club_opened_reschedule(p_fixture_id, v_club)' IN v_def) = 0 THEN
    RAISE EXCEPTION 'propose: home-first gate not found';
  END IF;
  v_def := regexp_replace(
    v_def,
    'IF v_club <> v_fixture\.home_club_short_name\s+AND NOT public\.match_schedule_club_opened_reschedule\(p_fixture_id, v_club\)\s+THEN',
    E'IF v_club <> v_fixture.home_club_short_name\n       AND NOT public.match_schedule_club_opened_reschedule(p_fixture_id, v_club)\n       AND NOT public.match_schedule_away_may_open_proposal(p_fixture_id)\n    THEN'
  );
  IF position('match_schedule_away_may_open_proposal' IN v_def) = 0 THEN
    RAISE EXCEPTION 'propose: away opening was not added';
  END IF;
  EXECUTE v_def;
END;
$away_open$;

CREATE OR REPLACE FUNCTION public.fixture_apply_unplayed_void(
  p_fixture_id bigint,
  p_reason text DEFAULT 'Unplayed — strikes and effort level, match void'
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_fixture public.competition_fixtures;
BEGIN
  SELECT * INTO v_fixture
  FROM public.competition_fixtures
  WHERE id = p_fixture_id
  FOR UPDATE;

  IF NOT FOUND OR v_fixture.status = 'played' THEN
    RETURN;
  END IF;

  UPDATE public.competition_result_submissions
  SET status = 'rejected',
      reject_reason = 'Superseded by unplayed void',
      responded_at = now()
  WHERE fixture_id = p_fixture_id
    AND status = 'pending';

  UPDATE public.competition_fixtures
  SET status = 'played',
      is_void = true,
      is_forfeit = false,
      home_goals = NULL,
      away_goals = NULL,
      forfeit_loser_club = NULL,
      result_auto_closed = true
  WHERE id = p_fixture_id;

  PERFORM public.owner_inbox_send(
    'match_noshow_fixture_forfeit',
    'Match void — neither club is given the win',
    coalesce(p_reason, 'Strikes were level and effort was level.')
      || ' The match is void. Neither club takes a point.',
    v_fixture.home_club_short_name,
    NULL, p_fixture_id, NULL, NULL, NULL,
    'fixture_schedule.html?fixture=' || p_fixture_id::text,
    'unplayedvoid:' || p_fixture_id::text || ':home',
    v_fixture.gpsl_month, v_fixture.season_id, NULL
  );
  PERFORM public.owner_inbox_send(
    'match_noshow_fixture_forfeit',
    'Match void — neither club is given the win',
    coalesce(p_reason, 'Strikes were level and effort was level.')
      || ' The match is void. Neither club takes a point.',
    v_fixture.away_club_short_name,
    NULL, p_fixture_id, NULL, NULL, NULL,
    'fixture_schedule.html?fixture=' || p_fixture_id::text,
    'unplayedvoid:' || p_fixture_id::text || ':away',
    v_fixture.gpsl_month, v_fixture.season_id, NULL
  );
END;
$function$;

DO $award$
DECLARE
  v_def text;
BEGIN
  SELECT replace(pg_get_functiondef(
    'public.match_schedule_pick_window_loser(bigint,bigint,text)'::regprocedure
  ), E'\r\n', E'\n') INTO v_def;

  IF position('fixture strike count' IN v_def) = 0 THEN
    IF position('v_home := public.match_schedule_club_activity_tuple(' IN v_def) = 0 THEN
      RAISE EXCEPTION 'window loser: activity step not found';
    END IF;
    v_def := replace(
      v_def,
      'v_home := public.match_schedule_club_activity_tuple(',
      $ins$-- fixture strike count (more strikes loses; level falls through to effort)
  IF public.match_schedule_fixture_strike_count(v_f.id, v_f.home_club_short_name)
     IS DISTINCT FROM public.match_schedule_fixture_strike_count(v_f.id, v_f.away_club_short_name) THEN
    RETURN CASE
      WHEN public.match_schedule_fixture_strike_count(v_f.id, v_f.home_club_short_name)
           > public.match_schedule_fixture_strike_count(v_f.id, v_f.away_club_short_name)
        THEN v_f.home_club_short_name
      ELSE v_f.away_club_short_name
    END;
  END IF;

  v_home := public.match_schedule_club_activity_tuple($ins$
    );
    EXECUTE v_def;
  END IF;

  SELECT replace(pg_get_functiondef(
    'public.competition_enforce_scheduling_window_awards(bigint,text)'::regprocedure
  ), E'\r\n', E'\n') INTO v_def;

  IF position('fixture_apply_unplayed_void' IN v_def) = 0 THEN
    IF position('fixture_apply_score_draw_0_0' IN v_def) = 0 THEN
      RAISE EXCEPTION 'window awards: 0-0 call not found';
    END IF;
    v_def := replace(v_def, 'fixture_apply_score_draw_0_0', 'fixture_apply_unplayed_void');
    v_def := regexp_replace(v_def, 'activity tied[^'']*', 'strikes and effort level, match void');
    EXECUTE v_def;
  END IF;
END;
$award$;

CREATE OR REPLACE FUNCTION public.match_schedule_no_show_ladder_json(p_fixture_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_sched public.competition_fixture_schedule;
  v_fixture public.competition_fixtures;
  v_home_n int := 0;
  v_away_n int := 0;
  v_home_owner uuid;
  v_away_owner uuid;
  v_home_strikes int := 0;
  v_away_strikes int := 0;
BEGIN
  SELECT * INTO v_fixture FROM public.competition_fixtures WHERE id = p_fixture_id;
  SELECT * INTO v_sched FROM public.competition_fixture_schedule WHERE fixture_id = p_fixture_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('play_attempt_count', 0, 'ladder_active', false);
  END IF;

  v_home_n := public.match_schedule_fixture_strike_count(p_fixture_id, v_fixture.home_club_short_name);
  v_away_n := public.match_schedule_fixture_strike_count(p_fixture_id, v_fixture.away_club_short_name);

  v_home_owner := public.match_schedule_club_owner_id(v_fixture.home_club_short_name);
  v_away_owner := public.match_schedule_club_owner_id(v_fixture.away_club_short_name);

  SELECT coalesce(s.strike_count, 0) INTO v_home_strikes
  FROM public.competition_owner_season_strikes s
  WHERE s.season_id = v_fixture.season_id AND s.owner_id = v_home_owner;
  SELECT coalesce(s.strike_count, 0) INTO v_away_strikes
  FROM public.competition_owner_season_strikes s
  WHERE s.season_id = v_fixture.season_id AND s.owner_id = v_away_owner;

  RETURN jsonb_build_object(
    'play_attempt_count', coalesce(v_sched.play_attempt_count, 0),
    'ladder_active', coalesce(v_sched.play_attempt_count, 0) >= 1,
    'attempt3_active', coalesce(v_sched.play_attempt_count, 0) >= 3 OR coalesce(v_sched.open_play_active, false),
    'open_play_active', coalesce(v_sched.open_play_active, false),
    'open_play_deadline_gpsl_month', v_sched.open_play_deadline_gpsl_month,
    'home_no_show_count', v_home_n,
    'away_no_show_count', v_away_n,
    'home_season_strikes', coalesce(v_home_strikes, 0),
    'away_season_strikes', coalesce(v_away_strikes, 0),
    'no_show_club_short_name', v_sched.no_show_club_short_name
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.my_club_strike_board()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_club text := nullif(btrim(coalesce(public.my_club_shortname(), '')), '');
  v_season bigint;
  v_owner uuid;
  v_season_n integer := 0;
  v_rows jsonb := '[]'::jsonb;
BEGIN
  IF v_club IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'season_strikes', 0, 'fixtures', '[]'::jsonb);
  END IF;

  SELECT id INTO v_season
  FROM public.competition_seasons
  WHERE is_current
  ORDER BY id DESC
  LIMIT 1;

  v_owner := public.match_schedule_club_owner_id(v_club);
  SELECT coalesce(s.strike_count, 0) INTO v_season_n
  FROM public.competition_owner_season_strikes s
  WHERE s.season_id = v_season AND s.owner_id = v_owner;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'fixture_id', f.id,
    'fixture_strikes', public.match_schedule_fixture_strike_count(f.id, v_club)
  )), '[]'::jsonb)
  INTO v_rows
  FROM public.competition_fixtures f
  WHERE f.season_id = v_season
    AND f.status = 'scheduled'
    AND v_club IN (f.home_club_short_name, f.away_club_short_name);

  RETURN jsonb_build_object(
    'ok', true,
    'season_strikes', coalesce(v_season_n, 0),
    'fixture_cap', 3,
    'season_step', 5,
    'fixtures', v_rows
  );
END;
$function$;

