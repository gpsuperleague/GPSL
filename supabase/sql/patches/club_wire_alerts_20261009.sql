-- =============================================================================
-- Club Wire — live outbid / outcome alerts for owners (dashboard + nav badge)
-- =============================================================================
-- One small alert row per owner + market + subject + kind (repeat outbids on
-- the same player update the row instead of stacking). Written by triggers on
-- the bid tables; the site polls club_wire_list() about once a minute.
--
--   Open auctions (live "outbid"):
--     player draft, transfer list, club auction, manager draft / market,
--     snap special auctions.
--     Retaking the lead (incl. your own max bid / auto-bid answering) clears
--     your outbid alert, so max-bid wars end on the true result.
--   Private / sealed (result only, nothing leaked while live):
--     direct offers accepted / rejected,
--     lowest-unique + blind gauntlet special auctions (won / lost at settle),
--     expiring-contract wage bids (won / lost at rollover).
--
-- Every trigger body is wrapped in an exception block: an alert can never
-- block or slow a bid beyond one indexed lookup. Not sent to the Inbox.
--
-- Run off-peak (creates indexes on the bid tables). Safe re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.club_wire_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL,
  club_short_name text,
  market text NOT NULL,
  kind text NOT NULL,
  subject_key text NOT NULL,
  subject_name text,
  amount numeric,
  by_label text,
  href text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  dismissed_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS club_wire_alerts_live_uidx
  ON public.club_wire_alerts (owner_id, market, subject_key, kind)
  WHERE dismissed_at IS NULL;

CREATE INDEX IF NOT EXISTS club_wire_alerts_owner_recent_idx
  ON public.club_wire_alerts (owner_id, updated_at DESC);

ALTER TABLE public.club_wire_alerts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS club_wire_alerts_select_own ON public.club_wire_alerts;
CREATE POLICY club_wire_alerts_select_own
  ON public.club_wire_alerts FOR SELECT TO authenticated
  USING (owner_id = auth.uid());

REVOKE INSERT, UPDATE, DELETE ON public.club_wire_alerts FROM anon, authenticated;
GRANT SELECT ON public.club_wire_alerts TO authenticated;

