-- =============================================================================
-- GPSL Sport — paired story packs + cooldown picker
--
-- • Packs keep headline/subhead/body glued (never mix across packs)
-- • Same pack cannot appear twice in one edition (exclude list)
-- • Packs used in the last N published editions are deprioritised (cooldown)
-- • Seeded from gpsl_sport_templates_FEEDBACK.csv (human-voice variants)
--
-- Safe re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.gpsl_sport_template_packs (
  pack_id text PRIMARY KEY,
  scenario text NOT NULL,
  headline text NOT NULL,
  subhead text NOT NULL DEFAULT '',
  body text NOT NULL,
  priority smallint NOT NULL DEFAULT 5,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gpsl_sport_template_packs_scenario_idx
  ON public.gpsl_sport_template_packs (scenario)
  WHERE active;

CREATE TABLE IF NOT EXISTS public.gpsl_sport_template_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edition_id bigint REFERENCES public.gpsl_sport_editions (id) ON DELETE CASCADE,
  season_id bigint,
  gpsl_month text,
  scenario text NOT NULL,
  pack_id text NOT NULL REFERENCES public.gpsl_sport_template_packs (pack_id),
  slot text NOT NULL DEFAULT 'lead',
  used_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gpsl_sport_template_usage_recent_idx
  ON public.gpsl_sport_template_usage (scenario, used_at DESC);

COMMENT ON TABLE public.gpsl_sport_template_packs IS
  'Paired GPSL Sport copy packs (headline+subhead+body) for random selection.';
COMMENT ON TABLE public.gpsl_sport_template_usage IS
  'Tracks which packs appeared in which editions for cooldown / no-repeat.';

