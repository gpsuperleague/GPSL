CREATE OR REPLACE FUNCTION public.gpsl_sport_compose_story_from_packs(
  p_scenario text,
  p_seed text,
  p_vars jsonb,
  p_season_id bigint DEFAULT NULL,
  p_exclude_pack_ids text[] DEFAULT '{}',
  p_cooldown_editions int DEFAULT 3
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_candidates text[];
  v_cooled text[];
  v_pick text;
  v_row public.gpsl_sport_template_packs;
  v_cooldown int := greatest(coalesce(p_cooldown_editions, 3), 0);
  v_exclude text[] := coalesce(p_exclude_pack_ids, '{}');
BEGIN
  IF coalesce(nullif(btrim(p_scenario), ''), '') = '' THEN
    RETURN NULL;
  END IF;

  IF to_regclass('public.gpsl_sport_template_packs') IS NULL THEN
    RETURN NULL;
  END IF;

  -- Packs used in the last N published editions for this scenario
  IF v_cooldown > 0
     AND to_regclass('public.gpsl_sport_template_usage') IS NOT NULL
     AND to_regclass('public.gpsl_sport_editions') IS NOT NULL THEN
    SELECT coalesce(array_agg(DISTINCT u.pack_id), '{}')
    INTO v_cooled
    FROM public.gpsl_sport_template_usage u
    WHERE u.scenario = p_scenario
      AND u.edition_id IN (
        SELECT e.id
        FROM public.gpsl_sport_editions e
        ORDER BY e.published_at DESC NULLS LAST, e.id DESC
        LIMIT v_cooldown
      );
  ELSE
    v_cooled := '{}';
  END IF;

  SELECT coalesce(array_agg(p.pack_id ORDER BY p.priority DESC, p.pack_id), '{}')
  INTO v_candidates
  FROM public.gpsl_sport_template_packs p
  WHERE p.active
    AND p.scenario = p_scenario
    AND NOT (p.pack_id = ANY (v_exclude))
    AND NOT (p.pack_id = ANY (v_cooled));

  -- Soft fallback: ignore cooldown if it wiped the bank
  IF coalesce(array_length(v_candidates, 1), 0) = 0 THEN
    SELECT coalesce(array_agg(p.pack_id ORDER BY p.priority DESC, p.pack_id), '{}')
    INTO v_candidates
    FROM public.gpsl_sport_template_packs p
    WHERE p.active
      AND p.scenario = p_scenario
      AND NOT (p.pack_id = ANY (v_exclude));
  END IF;

  IF coalesce(array_length(v_candidates, 1), 0) = 0 THEN
    RETURN NULL;
  END IF;

  v_pick := v_candidates[
    1 + (abs(hashtext(coalesce(p_seed, p_scenario))) % array_length(v_candidates, 1))
  ];

  SELECT * INTO v_row
  FROM public.gpsl_sport_template_packs p
  WHERE p.pack_id = v_pick;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  RETURN jsonb_build_object(
    'pack_id', v_row.pack_id,
    'scenario', v_row.scenario,
    'headline', public.gpsl_sport_apply_template(v_row.headline, p_vars),
    'subhead', public.gpsl_sport_apply_template(v_row.subhead, p_vars),
    'body', public.gpsl_sport_apply_template(v_row.body, p_vars)
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.gpsl_sport_record_pack_usage(
  p_edition_id bigint,
  p_season_id bigint,
  p_gpsl_month text,
  p_scenario text,
  p_pack_id text,
  p_slot text DEFAULT 'lead'
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF p_edition_id IS NULL OR coalesce(nullif(btrim(p_pack_id), ''), '') IS NULL THEN
    RETURN;
  END IF;
  IF to_regclass('public.gpsl_sport_template_usage') IS NULL THEN
    RETURN;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.gpsl_sport_template_packs p WHERE p.pack_id = p_pack_id
  ) THEN
    RETURN;
  END IF;

  INSERT INTO public.gpsl_sport_template_usage (
    edition_id, season_id, gpsl_month, scenario, pack_id, slot
  ) VALUES (
    p_edition_id, p_season_id, lower(nullif(btrim(p_gpsl_month), '')),
    coalesce(nullif(btrim(p_scenario), ''), 'unknown'),
    p_pack_id,
    coalesce(nullif(btrim(p_slot), ''), 'lead')
  );
END;
$function$;

