-- ---------------------------------------------------------------------------
-- 2) Idempotent Building Society prize helper
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.competition_pay_owner_award_credits(
  p_owner_id uuid,
  p_amount numeric,
  p_entry_type text,
  p_description text,
  p_dedupe_key text,
  p_season_id bigint DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_amt numeric(14, 2) := round(coalesce(p_amount, 0)::numeric, 2);
  v_type text := nullif(btrim(coalesce(p_entry_type, '')), '');
  v_key text := nullif(btrim(coalesce(p_dedupe_key, '')), '');
  v_ledger bigint;
BEGIN
  IF p_owner_id IS NULL OR v_type IS NULL OR v_key IS NULL OR v_amt <= 0 THEN
    RETURN NULL;
  END IF;

  IF to_regprocedure(
    'public._post_owner_ledger_internal(uuid,text,numeric,text,jsonb,bigint,boolean)'
  ) IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT l.id INTO v_ledger
  FROM public.owner_finance_ledger l
  WHERE l.owner_id = p_owner_id
    AND l.entry_type = v_type
    AND coalesce(l.metadata ->> 'dedupe_key', '') = v_key
  ORDER BY l.id
  LIMIT 1;

  IF v_ledger IS NOT NULL THEN
    RETURN v_ledger;
  END IF;

  v_ledger := public._post_owner_ledger_internal(
    p_owner_id,
    v_type,
    v_amt,
    nullif(btrim(coalesce(p_description, '')), ''),
    coalesce(p_metadata, '{}'::jsonb) || jsonb_build_object(
      'dedupe_key', v_key,
      'source', 'owner_award_prize'
    ),
    p_season_id,
    true
  );

  RETURN v_ledger;
END;
$function$;

GRANT EXECUTE ON FUNCTION public.competition_pay_owner_award_credits(
  uuid, numeric, text, text, text, bigint, jsonb
) TO authenticated;

-- ---------------------------------------------------------------------------
-- 3) Owner of the Month — pay ₿2,500 on award
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.competition_compute_owner_of_month(
  p_season_id bigint,
  p_gpsl_month text,
  p_division_scope text DEFAULT 'superleague'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_month text := lower(nullif(btrim(coalesce(p_gpsl_month, '')), ''));
  v_scope text := lower(nullif(btrim(coalesce(p_division_scope, '')), ''));
  v_season_label text;
  v_best record;
  v_owner_id uuid;
  v_owner_tag text;
  v_award_id bigint;
  v_prize numeric(14, 2) := 2500;
  v_ledger bigint;
  v_scope_label text;
BEGIN
  IF p_season_id IS NULL OR v_month IS NULL OR v_month = 'playoffs' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_args');
  END IF;

  IF v_scope IS DISTINCT FROM 'superleague' AND v_scope IS DISTINCT FROM 'championship' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_scope');
  END IF;

  SELECT s.label INTO v_season_label
  FROM public.competition_seasons s
  WHERE s.id = p_season_id;

  WITH club_month AS (
    SELECT
      x.club_short_name,
      count(*)::smallint AS played,
      count(*) FILTER (WHERE x.pts = 3)::smallint AS won,
      count(*) FILTER (WHERE x.pts = 1)::smallint AS drawn,
      count(*) FILTER (WHERE x.pts = 0)::smallint AS lost,
      coalesce(sum(x.gf), 0)::smallint AS gf,
      coalesce(sum(x.ga), 0)::smallint AS ga,
      coalesce(sum(x.pts), 0)::smallint AS pts
    FROM (
      SELECT
        f.home_club_short_name AS club_short_name,
        coalesce(f.home_goals, 0) AS gf,
        coalesce(f.away_goals, 0) AS ga,
        CASE
          WHEN f.home_goals > f.away_goals THEN 3
          WHEN f.home_goals = f.away_goals THEN 1
          ELSE 0
        END AS pts
      FROM public.competition_fixtures f
      WHERE f.season_id = p_season_id
        AND f.gpsl_month = v_month
        AND f.competition_type = 'league'
        AND f.status = 'played'
        AND f.home_goals IS NOT NULL
        AND f.away_goals IS NOT NULL
      UNION ALL
      SELECT
        f.away_club_short_name,
        coalesce(f.away_goals, 0),
        coalesce(f.home_goals, 0),
        CASE
          WHEN f.away_goals > f.home_goals THEN 3
          WHEN f.away_goals = f.home_goals THEN 1
          ELSE 0
        END
      FROM public.competition_fixtures f
      WHERE f.season_id = p_season_id
        AND f.gpsl_month = v_month
        AND f.competition_type = 'league'
        AND f.status = 'played'
        AND f.home_goals IS NOT NULL
        AND f.away_goals IS NOT NULL
    ) x
    INNER JOIN public.competition_club_seasons s
      ON s.season_id = p_season_id
     AND s.club_short_name = x.club_short_name
     AND (
       (v_scope = 'superleague' AND s.division = 'superleague')
       OR (
         v_scope = 'championship'
         AND s.division IN ('championship_a', 'championship_b')
       )
     )
    GROUP BY x.club_short_name
    HAVING count(*) > 0
  )
  SELECT cm.*
  INTO v_best
  FROM club_month cm
  INNER JOIN public."Clubs" c ON c."ShortName" = cm.club_short_name
  WHERE c.owner_id IS NOT NULL
  ORDER BY cm.pts DESC, (cm.gf - cm.ga) DESC, cm.gf DESC, cm.club_short_name
  LIMIT 1;

  IF v_best.club_short_name IS NULL THEN
    RETURN jsonb_build_object(
      'ok', false,
      'reason', 'no_fixtures',
      'division_scope', v_scope,
      'gpsl_month', v_month
    );
  END IF;

  SELECT c.owner_id INTO v_owner_id
  FROM public."Clubs" c
  WHERE c."ShortName" = v_best.club_short_name;

  IF v_owner_id IS NULL THEN
    RETURN jsonb_build_object(
      'ok', false,
      'reason', 'no_owner',
      'division_scope', v_scope,
      'club_short_name', v_best.club_short_name
    );
  END IF;

  v_owner_tag := coalesce(
    nullif(btrim(public.owner_registry_resolve_tag(v_owner_id)), ''),
    'Owner'
  );

  v_scope_label := CASE v_scope
    WHEN 'championship' THEN 'Championship'
    ELSE 'Super League'
  END;

  INSERT INTO public.competition_owner_month_award (
    season_id, season_label, gpsl_month, division_scope,
    owner_id, owner_tag, club_short_name,
    played, won, drawn, lost, gf, ga, pts, detail
  )
  VALUES (
    p_season_id,
    coalesce(v_season_label, 'Season'),
    v_month,
    v_scope,
    v_owner_id,
    v_owner_tag,
    v_best.club_short_name,
    v_best.played,
    v_best.won,
    v_best.drawn,
    v_best.lost,
    v_best.gf,
    v_best.ga,
    v_best.pts,
    jsonb_build_object(
      'gd', v_best.gf - v_best.ga,
      'prize_amount', v_prize
    )
  )
  ON CONFLICT (season_id, gpsl_month, division_scope) DO UPDATE SET
    owner_id = EXCLUDED.owner_id,
    owner_tag = EXCLUDED.owner_tag,
    club_short_name = EXCLUDED.club_short_name,
    played = EXCLUDED.played,
    won = EXCLUDED.won,
    drawn = EXCLUDED.drawn,
    lost = EXCLUDED.lost,
    gf = EXCLUDED.gf,
    ga = EXCLUDED.ga,
    pts = EXCLUDED.pts,
    detail = EXCLUDED.detail,
    season_label = EXCLUDED.season_label
  RETURNING id INTO v_award_id;

  v_ledger := public.competition_pay_owner_award_credits(
    v_owner_id,
    v_prize,
    'owner_of_month_prize',
    format(
      'Owner of the Month — %s %s (₿%s)',
      v_scope_label,
      initcap(v_month),
      to_char(v_prize, 'FM999,999,999')
    ),
    format('ootm_prize:%s:%s:%s', p_season_id, v_month, v_scope),
    p_season_id,
    jsonb_build_object(
      'award', 'owner_of_the_month',
      'award_id', v_award_id,
      'season_id', p_season_id,
      'gpsl_month', v_month,
      'division_scope', v_scope,
      'club_short_name', v_best.club_short_name
    )
  );

  IF v_ledger IS NOT NULL THEN
    UPDATE public.competition_owner_month_award
    SET detail = coalesce(detail, '{}'::jsonb) || jsonb_build_object(
      'prize_amount', v_prize,
      'prize_ledger_id', v_ledger
    )
    WHERE id = v_award_id;
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'gpsl_month', v_month,
    'division_scope', v_scope,
    'owner_id', v_owner_id,
    'owner_tag', v_owner_tag,
    'club_short_name', v_best.club_short_name,
    'pts', v_best.pts,
    'record', format('%s-%s-%s', v_best.won, v_best.drawn, v_best.lost),
    'prize_amount', v_prize,
    'prize_ledger_id', v_ledger
  );
END;
$function$;

GRANT EXECUTE ON FUNCTION public.competition_compute_owner_of_month(bigint, text, text)
  TO authenticated;

-- ---------------------------------------------------------------------------
-- 4) Owner of the Season — most places beaten vs expectation
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.competition_compute_owner_of_season(
  p_season_id bigint,
  p_division_scope text DEFAULT 'superleague'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_scope text := lower(nullif(btrim(coalesce(p_division_scope, '')), ''));
  v_season_label text;
  v_best record;
  v_owner_tag text;
  v_award_id bigint;
  v_prize numeric(14, 2);
  v_ledger bigint;
  v_scope_label text;
  v_metrics jsonb;
  r record;
  v_exp int;
  v_act int;
  v_over int;
  v_gap numeric;
BEGIN
  IF p_season_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_args');
  END IF;

  IF v_scope IS DISTINCT FROM 'superleague' AND v_scope IS DISTINCT FROM 'championship' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'bad_scope');
  END IF;

  SELECT s.label INTO v_season_label
  FROM public.competition_seasons s
  WHERE s.id = p_season_id;

  IF v_season_label IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'no_season');
  END IF;

  v_prize := CASE v_scope
    WHEN 'championship' THEN 7500::numeric
    ELSE 10000::numeric
  END;
  v_scope_label := CASE v_scope
    WHEN 'championship' THEN 'Championship'
    ELSE 'Super League'
  END;

  -- Rank owned clubs by places beaten (expected − actual); must overachieve.
  CREATE TEMP TABLE IF NOT EXISTS _oot_season_cands (
    club_short_name text PRIMARY KEY,
    owner_id uuid NOT NULL,
    expected_position int NOT NULL,
    actual_position int NOT NULL,
    position_overachievement int NOT NULL,
    performance_gap numeric,
    division text
  ) ON COMMIT DROP;
  -- safeupdate / pg_safeupdate rejects DELETE without a WHERE clause
  DELETE FROM _oot_season_cands WHERE true;

  FOR r IN
    SELECT
      s.club_short_name,
      s.division,
      c.owner_id
    FROM public.competition_club_seasons s
    INNER JOIN public."Clubs" c ON c."ShortName" = s.club_short_name
    WHERE s.season_id = p_season_id
      AND c.owner_id IS NOT NULL
      AND (
        (v_scope = 'superleague' AND s.division = 'superleague')
        OR (
          v_scope = 'championship'
          AND s.division IN ('championship_a', 'championship_b')
        )
      )
  LOOP
    BEGIN
      v_metrics := public.competition_stadium_season_metrics(
        r.club_short_name, p_season_id, r.division
      );
    EXCEPTION WHEN OTHERS THEN
      v_metrics := NULL;
    END;

    IF v_metrics IS NULL OR (v_metrics ? 'error') THEN
      CONTINUE;
    END IF;

    IF NOT (
      (v_metrics ->> 'expected_position') ~ '^-?\d+$'
      AND (v_metrics ->> 'actual_position') ~ '^-?\d+$'
    ) THEN
      CONTINUE;
    END IF;

    v_exp := (v_metrics ->> 'expected_position')::int;
    v_act := (v_metrics ->> 'actual_position')::int;
    v_over := v_exp - v_act;
    IF v_over <= 0 THEN
      CONTINUE;
    END IF;

    v_gap := CASE
      WHEN (v_metrics ->> 'performance_gap') ~ '^-?\d+(\.\d+)?$'
        THEN (v_metrics ->> 'performance_gap')::numeric
      ELSE NULL
    END;

    INSERT INTO _oot_season_cands (
      club_short_name, owner_id, expected_position, actual_position,
      position_overachievement, performance_gap, division
    )
    VALUES (
      r.club_short_name, r.owner_id, v_exp, v_act, v_over, v_gap, r.division
    )
    ON CONFLICT (club_short_name) DO NOTHING;
  END LOOP;

  SELECT
    c.club_short_name,
    c.owner_id,
    c.expected_position,
    c.actual_position,
    c.position_overachievement,
    c.performance_gap,
    c.division
  INTO v_best
  FROM _oot_season_cands c
  ORDER BY
    c.position_overachievement DESC,
    coalesce(c.performance_gap, -999999) DESC,
    c.actual_position ASC,
    c.club_short_name
  LIMIT 1;

  IF v_best.club_short_name IS NULL THEN
    RETURN jsonb_build_object(
      'ok', false,
      'reason', 'no_overachiever',
      'division_scope', v_scope,
      'season_id', p_season_id
    );
  END IF;

  v_owner_tag := coalesce(
    nullif(btrim(public.owner_registry_resolve_tag(v_best.owner_id)), ''),
    'Owner'
  );

  INSERT INTO public.competition_owner_season_award (
    season_id, season_label, division_scope,
    owner_id, owner_tag, club_short_name,
    expected_position, actual_position, position_overachievement,
    performance_gap, prize_amount, detail
  )
  VALUES (
    p_season_id,
    coalesce(v_season_label, 'Season'),
    v_scope,
    v_best.owner_id,
    v_owner_tag,
    v_best.club_short_name,
    v_best.expected_position,
    v_best.actual_position,
    v_best.position_overachievement,
    v_best.performance_gap,
    v_prize,
    jsonb_build_object(
      'division', v_best.division,
      'metric', 'expected_minus_actual_position'
    )
  )
  ON CONFLICT (season_id, division_scope) DO UPDATE SET
    owner_id = EXCLUDED.owner_id,
    owner_tag = EXCLUDED.owner_tag,
    club_short_name = EXCLUDED.club_short_name,
    expected_position = EXCLUDED.expected_position,
    actual_position = EXCLUDED.actual_position,
    position_overachievement = EXCLUDED.position_overachievement,
    performance_gap = EXCLUDED.performance_gap,
    prize_amount = EXCLUDED.prize_amount,
    detail = EXCLUDED.detail,
    season_label = EXCLUDED.season_label
  RETURNING id INTO v_award_id;

  v_ledger := public.competition_pay_owner_award_credits(
    v_best.owner_id,
    v_prize,
    'owner_of_season_prize',
    format(
      'Owner of the Season — %s %s (₿%s)',
      v_scope_label,
      coalesce(v_season_label, 'Season'),
      to_char(v_prize, 'FM999,999,999')
    ),
    format('oots_prize:%s:%s', p_season_id, v_scope),
    p_season_id,
    jsonb_build_object(
      'award', 'owner_of_the_season',
      'award_id', v_award_id,
      'season_id', p_season_id,
      'division_scope', v_scope,
      'club_short_name', v_best.club_short_name,
      'expected_position', v_best.expected_position,
      'actual_position', v_best.actual_position,
      'position_overachievement', v_best.position_overachievement
    )
  );

  IF v_ledger IS NOT NULL THEN
    UPDATE public.competition_owner_season_award
    SET detail = coalesce(detail, '{}'::jsonb) || jsonb_build_object(
      'prize_ledger_id', v_ledger
    )
    WHERE id = v_award_id;
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'season_id', p_season_id,
    'division_scope', v_scope,
    'owner_id', v_best.owner_id,
    'owner_tag', v_owner_tag,
    'club_short_name', v_best.club_short_name,
    'expected_position', v_best.expected_position,
    'actual_position', v_best.actual_position,
    'position_overachievement', v_best.position_overachievement,
    'performance_gap', v_best.performance_gap,
    'prize_amount', v_prize,
    'prize_ledger_id', v_ledger
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.competition_award_owners_of_season(
