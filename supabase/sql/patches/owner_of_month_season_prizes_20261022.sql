-- ---------------------------------------------------------------------------
-- 1) Owner of the Season table
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.competition_owner_season_award (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.competition_seasons (id) ON DELETE CASCADE,
  season_label text NOT NULL,
  division_scope text NOT NULL CHECK (division_scope IN ('superleague', 'championship')),
  owner_id uuid NOT NULL,
  owner_tag text NOT NULL,
  club_short_name text NOT NULL REFERENCES public."Clubs" ("ShortName"),
  expected_position smallint NOT NULL,
  actual_position smallint NOT NULL,
  position_overachievement smallint NOT NULL,
  performance_gap numeric(12, 2),
  prize_amount numeric(14, 2) NOT NULL DEFAULT 0,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT competition_owner_season_award_unique
    UNIQUE (season_id, division_scope)
);

CREATE INDEX IF NOT EXISTS competition_owner_season_award_owner_idx
  ON public.competition_owner_season_award (owner_id, season_id DESC);

ALTER TABLE public.competition_owner_season_award ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS competition_owner_season_award_select ON public.competition_owner_season_award;
CREATE POLICY competition_owner_season_award_select ON public.competition_owner_season_award
  FOR SELECT TO authenticated, anon USING (true);

DROP POLICY IF EXISTS competition_owner_season_award_admin ON public.competition_owner_season_award;
CREATE POLICY competition_owner_season_award_admin ON public.competition_owner_season_award
  FOR ALL TO authenticated
  USING (public.is_gpsl_admin())
  WITH CHECK (public.is_gpsl_admin());

DROP VIEW IF EXISTS public.competition_owner_season_awards_public;
CREATE VIEW public.competition_owner_season_awards_public
WITH (security_invoker = false)
AS
SELECT
  a.id,
  a.season_id,
  a.season_label,
  a.division_scope,
  a.owner_id,
  a.owner_tag,
  a.club_short_name,
  c."Club" AS club_name,
  a.expected_position,
  a.actual_position,
  a.position_overachievement,
