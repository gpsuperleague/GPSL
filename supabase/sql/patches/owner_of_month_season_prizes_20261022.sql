CREATE OR REPLACE FUNCTION public.owner_profile_personal_achievements(p_owner_id uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
  SELECT coalesce(jsonb_agg(x.item ORDER BY x.sort_season DESC, x.sort_ord, x.sort_month DESC), '[]'::jsonb)
  FROM (
    SELECT
      m.season_id AS sort_season,
      CASE lower(m.gpsl_month)
        WHEN 'august' THEN 1 WHEN 'september' THEN 2 WHEN 'october' THEN 3
        WHEN 'november' THEN 4 WHEN 'december' THEN 5 WHEN 'january' THEN 6
        WHEN 'february' THEN 7 WHEN 'march' THEN 8 WHEN 'april' THEN 9
        WHEN 'may' THEN 10 WHEN 'june' THEN 11 WHEN 'july' THEN 12
        ELSE 99
      END AS sort_month,
      1 AS sort_ord,
      jsonb_build_object(
        'achievement_type', 'owner_of_the_month',
        'label', format(
          'Owner of the Month — %s',
          CASE m.division_scope
            WHEN 'championship' THEN 'Championship'
            ELSE 'Super League'
          END
        ),
        'season_id', m.season_id,
        'season_label', m.season_label,
        'gpsl_month', m.gpsl_month,
        'division_scope', m.division_scope,
        'club_short_name', m.club_short_name,
        'club_name', c."Club",
        'prize_amount', coalesce(
          CASE
            WHEN (m.detail ->> 'prize_amount') ~ '^-?\d+(\.\d+)?$'
              THEN (m.detail ->> 'prize_amount')::numeric
            ELSE NULL
          END,
          2500
        ),
        'detail', jsonb_build_object(
          'pts', m.pts,
          'record', format('%s-%s-%s', m.won, m.drawn, m.lost)
        )
      ) AS item
    FROM public.competition_owner_month_award m
    LEFT JOIN public."Clubs" c ON c."ShortName" = m.club_short_name
    WHERE m.owner_id = p_owner_id

    UNION ALL

    SELECT
      s.season_id,
      0,
      0,
      jsonb_build_object(
        'achievement_type', 'owner_of_the_season',
        'label', format(
          'Owner of the Season — %s',
          CASE s.division_scope
            WHEN 'championship' THEN 'Championship'
            ELSE 'Super League'
          END
        ),
        'season_id', s.season_id,
        'season_label', s.season_label,
        'gpsl_month', NULL,
        'division_scope', s.division_scope,
        'club_short_name', s.club_short_name,
        'club_name', c2."Club",
        'prize_amount', s.prize_amount,
        'detail', jsonb_build_object(
          'expected_position', s.expected_position,
          'actual_position', s.actual_position,
          'position_overachievement', s.position_overachievement,
          'performance_gap', s.performance_gap
        )
      )
    FROM public.competition_owner_season_award s
    LEFT JOIN public."Clubs" c2 ON c2."ShortName" = s.club_short_name
    WHERE s.owner_id = p_owner_id
  ) x;
$function$;

