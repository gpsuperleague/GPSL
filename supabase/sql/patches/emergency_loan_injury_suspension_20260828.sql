-- =============================================================================
-- Emergency loans (injury / suspension shortfall)
--
-- When from August onward a club’s AVAILABLE players (not injured, not
-- suspended) drop below the 24 minimum, the owner may loan free agents
-- rated ≤66 for ₿2.5m (paid to central bank).
--
-- Duration (half-season):
--   Taken Aug–Dec  → returns end of December
--   Taken Jan–May  → returns end of May
--
-- Squad space:
--   Under 28 → fill empty slots
--   At 28    → allow one emergency overflow (28+1) only
--
-- Run once in Supabase SQL Editor. Safe re-run.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.club_emergency_loans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.competition_seasons (id) ON DELETE CASCADE,
  club_short_name text NOT NULL REFERENCES public."Clubs" ("ShortName") ON DELETE CASCADE,
  player_id text NOT NULL,
  loan_fee numeric NOT NULL DEFAULT 2500000,
  started_gpsl_month text NOT NULL,
  ends_gpsl_month text NOT NULL
    CHECK (ends_gpsl_month IN ('december', 'may')),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'completed', 'cancelled')),
  loan_ledger_id bigint,
  overflow_slot boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  UNIQUE (season_id, player_id)
);

CREATE INDEX IF NOT EXISTS club_emergency_loans_club_active_idx
  ON public.club_emergency_loans (club_short_name, season_id)
  WHERE status = 'active';

CREATE INDEX IF NOT EXISTS club_emergency_loans_ends_idx
  ON public.club_emergency_loans (season_id, ends_gpsl_month)
  WHERE status = 'active';

ALTER TABLE public.club_emergency_loans ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS club_emergency_loans_select ON public.club_emergency_loans;
CREATE POLICY club_emergency_loans_select ON public.club_emergency_loans
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS club_emergency_loans_admin ON public.club_emergency_loans;
CREATE POLICY club_emergency_loans_admin ON public.club_emergency_loans
  FOR ALL TO authenticated
  USING (public.is_gpsl_admin())
  WITH CHECK (public.is_gpsl_admin());

GRANT SELECT ON public.club_emergency_loans TO authenticated;

CREATE OR REPLACE FUNCTION public.emergency_loan_fee_amount()
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $$ SELECT 2500000::numeric; $$;

CREATE OR REPLACE FUNCTION public.emergency_loan_max_rating()
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $$ SELECT 66::numeric; $$;

-- ---------------------------------------------------------------------------
-- Half-season window helpers
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.emergency_loan_window_end_month(p_month text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE lower(btrim(coalesce(p_month, '')))
    WHEN 'august' THEN 'december'
    WHEN 'september' THEN 'december'
    WHEN 'october' THEN 'december'
    WHEN 'november' THEN 'december'
    WHEN 'december' THEN 'december'
    WHEN 'january' THEN 'may'
    WHEN 'february' THEN 'may'
    WHEN 'march' THEN 'may'
    WHEN 'april' THEN 'may'
    WHEN 'may' THEN 'may'
    ELSE NULL
  END;
$$;

CREATE OR REPLACE FUNCTION public.emergency_loan_window_open(p_month text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT public.emergency_loan_window_end_month(p_month) IS NOT NULL;
$$;

-- ---------------------------------------------------------------------------
-- Available (fit) players — not out injured, not suspended
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.club_player_is_currently_unavailable(p_player_id text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.competition_player_injuries i
    WHERE i.player_id = p_player_id
      AND i.status = 'active'
  )
  OR EXISTS (
    SELECT 1
    FROM public.competition_player_suspensions s
    WHERE s.player_id = p_player_id
      AND s.status = 'active'
      AND EXISTS (
        SELECT 1
        FROM public.competition_player_suspension_matches sm
        WHERE sm.suspension_id = s.id
          AND sm.served = false
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.club_available_player_count(p_club_short_name text)
RETURNS int
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT count(*)::int
  FROM public."Players" p
  WHERE p."Contracted_Team" = btrim(p_club_short_name)
    AND NOT public.club_player_is_currently_unavailable(p."Konami_ID"::text);
$$;

CREATE OR REPLACE FUNCTION public.club_active_emergency_loan_count(p_club_short_name text)
RETURNS int
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT count(*)::int
  FROM public.club_emergency_loans l
  JOIN public.competition_seasons s ON s.id = l.season_id
  WHERE l.club_short_name = btrim(p_club_short_name)
    AND l.status = 'active'
    AND s.is_current = true;
$$;

